// The spoke paths a design cites in its own repository, as
// `<repository-id>@<12-hex>:<path>`, each with its line. The label lines are
// left out: a `Rules:` value has the same shape and names a folder, not a read,
// and a `Guardrails:` value has the same shape and names Prime's rules.
function spokeCitations(lines, repository) {
  if (repository === null) return [];
  const labels = [CONFIG.rulesLabel, CONFIG.contextLabel, CONFIG.guardrailsLabel, CONFIG.hubCommitLabel, CONFIG.discoveryLabel].map((l) => `${l}:`);
  const found = [];
  lines.forEach((line, i) => {
    if (labels.some((l) => line.startsWith(l))) return;
    for (const m of line.matchAll(CONFIG.discoveryCite)) {
      if (m[1] !== repository) continue;
      const path = m[3].replace(/\.+$/, '');
      found.push({ no: i + 1, cite: `${m[1]}@${m[2]}:${path}`, path });
    }
  });
  return found;
}

// The one value of each `<label>:` head line in the map, or a failure that
// says why there is not one.
function mapHeadLine(lines, mapPath, label, expected, report) {
  const re = new RegExp(`^${label}:[ \\t]*(\\S.*?)\\s*$`);
  const hits = [];
  lines.forEach((line, i) => {
    const m = line.match(re);
    if (m) hits.push({ no: i + 1, value: m[1] });
  });
  if (hits.length === 0) {
    report.fail(`${mapPath} carries no "${label}:" line. Write exactly one "${label}: ${expected}" line.`);
    return null;
  }
  if (hits.length > 1) {
    report.fail(`${mapPath} carries ${hits.length} "${label}:" lines (lines ${hits.map((h) => h.no).join(', ')}). A map has one "${label}:" line.`);
    return null;
  }
  return hits[0];
}

// The rows of one map table, as [{ no, cells }], or null when the section
// cannot be read. A section that may be empty holds the literal token NONE
// and no table.
function mapTable(lines, mapPath, spec, report) {
  const ranges = sectionRanges(lines, spec.title);
  const header = `| ${spec.columns.join(' | ')} |`;
  if (ranges.length === 0) {
    report.fail(`${mapPath} carries no "## ${spec.title}" section. Write the section with the table "${header}".`);
    return null;
  }
  if (ranges.length > 1) {
    report.fail(`${mapPath} carries the "## ${spec.title}" section ${ranges.length} times (lines ${ranges.map((r) => r[0] + 1).join(', ')}). Write each section once.`);
    return null;
  }
  const range = ranges[0];
  const body = lines.slice(range[0] + 1, range[1] + 1).map((l) => l.trim()).filter((l) => l !== '');
  const blocks = tableBlocks(lines, range).filter((b) => {
    const cells = splitRow(b.rows[0].line);
    return cells !== null && cells.join('|') === spec.columns.join('|');
  });
  const hasNone = body.includes(CONFIG.discoveryNone);
  if (hasNone && !spec.none) {
    report.fail(`${mapPath}: the "${spec.title}" section is ${CONFIG.discoveryNone}. The map lists at least one row in the table "${header}".`);
    return null;
  }
  if (hasNone && body.length === 1) return [];
  if (hasNone) {
    report.fail(`${mapPath}: the "${spec.title}" section carries ${CONFIG.discoveryNone} and other content. Write the table "${header}" or ${CONFIG.discoveryNone} alone.`);
    return null;
  }
  if (blocks.length !== 1) {
    const or = spec.none ? ` or the token ${CONFIG.discoveryNone}` : '';
    const found = blocks.length === 0 ? 'no table' : `${blocks.length} tables`;
    report.fail(`${mapPath}: the "${spec.title}" section carries ${found} with the header "${header}". Write one table${or}.`);
    return null;
  }
  const block = blocks[0];
  if (block.rows.length < 2 || !isSeparatorRow(splitRow(block.rows[1].line), spec.columns.length)) {
    report.fail(`${mapPath} line ${block.rows[0].no}: the "${spec.title}" header has no separator row under it, so the page shows text and not a table.`);
    return null;
  }
  // A row with the wrong number of cells is a rejectMalformedRows finding.
  const rows = block.rows.slice(2)
    .map((r) => ({ no: r.no, cells: splitRow(r.line) }))
    .filter((r) => r.cells !== null && r.cells.length === spec.columns.length);
  if (rows.length === 0 && !spec.none) {
    report.fail(`${mapPath}: the "${spec.title}" table has no rows. The map lists at least one.`);
  }
  return rows;
}

// A cell with the backticks around it removed, as a reader sees a code span.
function unquoted(cell) {
  const m = cell.match(/^`([^`]*)`$/);
  return m ? m[1].trim() : cell;
}

// The design's `Discovery:` line and the map it pins. `design` is
// { path, lines, repository, rulesCommit, citedPaths }: the masked design, its
// repository id and its `Rules:` commit (each null when the design does not
// give one well formed), and the spoke paths it cites. Every rule runs, and
// each failure names the line and the fix.
function checkDiscoveryMap(ref, key, design, report) {
  const mapPath = `${CONFIG.designDir}/${key}${CONFIG.discoverySuffix}`;
  const lineRe = new RegExp(`^${CONFIG.discoveryLabel}:[ \\t]*(\\S.*?)\\s*$`);
  const claims = [];
  design.lines.forEach((line, i) => {
    const m = line.match(lineRe);
    if (m) claims.push({ no: i + 1, value: m[1] });
  });
  const entry = treeEntry(ref, mapPath);
  const expected = `"${CONFIG.discoveryLabel}: ${key}${CONFIG.discoverySuffix}@<12-hex>"`;

  if (claims.length === 0) {
    if (entry !== null) {
      report.fail(`${design.path} carries no "${CONFIG.discoveryLabel}:" line, and ${mapPath} is on ${ref}. A design pins the map it was written from, so pin it from the design: ${expected}, with the first 12 characters of \`git hash-object ${mapPath}\`.`);
    } else {
      report.note(`no discovery map for ${key}. The design was written before /dev-spec wrote maps. A new design pins one.`);
    }
    return;
  }
  if (claims.length > 1) {
    report.fail(`${design.path} carries ${claims.length} "${CONFIG.discoveryLabel}:" lines (lines ${claims.map((c) => c.no).join(', ')}). A design pins one discovery map.`);
    return;
  }
  const { no, value } = claims[0];
  const at = `${design.path} line ${no}`;
  const pin = value.match(CONFIG.discoveryPin);
  if (pin === null) {
    report.fail(`${at}: "${CONFIG.discoveryLabel}: ${value}" is not ${expected}. Pin the map with the first 12 characters of \`git hash-object ${mapPath}\`.`);
    return;
  }
  if (pin[1] !== key) {
    report.fail(`${at}: "${CONFIG.discoveryLabel}: ${value}" pins the map of ${pin[1]}. A design pins its own map, ${key}${CONFIG.discoverySuffix}.`);
    return;
  }
  if (entry === null) {
    report.fail(`${at} pins ${mapPath}, which is not on ${ref}. Merge the map with the design.`);
    return;
  }
  const text = readArtefact(ref, entry, report, 'discovery map');
  if (text === null) return;
  const actual = blobHash(ref, mapPath);
  if (actual === null) {
    report.fail(`could not read the revision of ${mapPath} on ${ref}`);
    return;
  }
  if (!actual.startsWith(pin[2])) {
    report.fail(`${at} pins ${mapPath} at ${pin[2]}, and ${ref} carries ${actual.slice(0, 12)}: the map changed after the design pinned it. Copy the first 12 characters of the map's new \`git hash-object\` value into the design. Then the design needs a new review.`);
  }

  const lines = maskNonContent(text);
  rejectHiddenMarkup(lines, mapPath, report);
  rejectMalformedRows(lines, mapPath, report);

  // The head lines: the work item, the repository and the commit the seat read.
  const ticket = mapHeadLine(lines, mapPath, 'Ticket', key, report);
  if (ticket !== null && ticket.value !== key) {
    report.fail(`${mapPath} line ${ticket.no}: "Ticket: ${ticket.value}" is not ${key}. A map is evidence about one work item.`);
  }
  const repository = mapHeadLine(lines, mapPath, 'Repository', design.repository || '<repository-id>', report);
  if (repository !== null && design.repository !== null && repository.value !== design.repository) {
    report.fail(`${mapPath} line ${repository.no}: "Repository: ${repository.value}" is not ${design.repository}, the repository the design lands in. A map reads the design's own repository.`);
  }
  const commit = mapHeadLine(lines, mapPath, 'Commit', '<40-hex>', report);
  if (commit !== null) {
    if (commit.value.match(CONFIG.discoveryCommit) === null) {
      report.fail(`${mapPath} line ${commit.no}: "Commit: ${commit.value}" is not a commit hash of 40 lowercase hex characters.`);
    } else if (design.rulesCommit !== null && !commit.value.startsWith(design.rulesCommit)) {
      report.fail(`${mapPath} line ${commit.no}: "Commit: ${commit.value}" does not start with ${design.rulesCommit}, the commit on the design's "${CONFIG.rulesLabel}:" line. Read the code at the commit the design read the rules at.`);
    }
  }

  // The four tables.
  const [filesSpec, searchSpec, ruledSpec, reusedSpec] = CONFIG.discoveryTables;
  const filesRead = mapTable(lines, mapPath, filesSpec, report);
  const searches = mapTable(lines, mapPath, searchSpec, report);
  const ruledOut = mapTable(lines, mapPath, ruledSpec, report);
  const reused = mapTable(lines, mapPath, reusedSpec, report);

  const checkPath = (r, path) => {
    if (path.match(CONFIG.discoveryPath) === null) {
      report.fail(`${mapPath} line ${r.no}: the path "${path}" is not a relative path in the repository. Write it as git prints it: no leading or trailing /, no . or .. segment, no doubled /, and no whitespace, comma or colon.`);
      return false;
    }
    return true;
  };
  const checkBlob = (r, blob) => {
    if (blob.match(CONFIG.discoveryBlob) === null) {
      report.fail(`${mapPath} line ${r.no}: the blob "${blob}" is not 12 lowercase hex characters. Copy the first 12 characters of the file's blob hash at the map's commit.`);
    }
  };
  const checkReason = (r, column, cell, what) => {
    if (cell.trim() === '' || isPlaceholder(cell)) {
      report.fail(`${mapPath} line ${r.no}: the "${column}" cell "${cell}" is empty or a placeholder. Say ${what}.`);
    }
  };

  const readPaths = new Set();
  for (const r of filesRead || []) {
    const [path, blob, why] = r.cells;
    if (checkPath(r, path)) readPaths.add(path);
    checkBlob(r, blob);
    checkReason(r, 'Why', why, 'why the seat read the file');
  }

  const searchSet = new Set();
  for (const r of searches || []) {
    const [cell, hits, kept] = r.cells;
    const search = unquoted(cell);
    searchSet.add(search);
    if (search.search(CONFIG.discoverySearch) !== 0) {
      report.fail(`${mapPath} line ${r.no}: the search "${search}" is not a scripts/read-spoke.mjs search. Write the arguments after the repository id, starting "--grep " or "--files ".`);
    }
    const counts = [['Hits', hits], ['Kept', kept]].filter(([, v]) => v.match(CONFIG.discoveryCount) === null);
    for (const [column, v] of counts) {
      report.fail(`${mapPath} line ${r.no}: the "${column}" cell "${v}" is not a whole number of 0 or more.`);
    }
    if (counts.length === 0 && Number(kept) > Number(hits)) {
      report.fail(`${mapPath} line ${r.no}: "Kept" is ${kept} and "Hits" is ${hits}. A search keeps no more hits than it found.`);
    }
  }

  for (const r of ruledOut || []) {
    const [path, blob, cell, reason] = r.cells;
    checkPath(r, path);
    checkBlob(r, blob);
    const search = unquoted(cell);
    if (searches !== null && !searchSet.has(search)) {
      report.fail(`${mapPath} line ${r.no}: the search "${search}" is not in the "${searchSpec.title}" table. A path is ruled out by a search the map lists.`);
    }
    checkReason(r, 'Reason', reason, 'why the path was ruled out');
  }

  for (const r of reused || []) {
    const [mapCell, path, pinCell] = r.cells;
    const other = mapCell.match(CONFIG.discoveryPin);
    const pathOk = checkPath(r, path);
    if (other === null) {
      report.fail(`${mapPath} line ${r.no}: the map "${mapCell}" is not "<OTHER-KEY>${CONFIG.discoverySuffix}@<12-hex>".`);
    } else if (other[1] === key) {
      report.fail(`${mapPath} line ${r.no}: the map "${mapCell}" is this story's own map. A map reuses the rows of another story's map.`);
    } else {
      // The pinned bytes are a map a person merged: the trunk carries them now,
      // or some commit on the trunk held them.
      const otherPath = `${CONFIG.designDir}/${other[1]}${CONFIG.discoverySuffix}`;
      const now = blobHash(ref, otherPath);
      if (now === null || !now.startsWith(other[2])) {
        const held = pinOnHistory(ref, otherPath, other[2]);
        if (held === null) {
          refuseToJudge(`${mapPath} reuses ${otherPath} at ${other[2]}, which ${ref} does not carry now, and this clone is shallow, so the gate cannot tell an earlier merged map from bytes nobody merged. Fetch full history (fetch-depth: 0) and re-run.`);
        } else if (!held) {
          report.fail(`${mapPath} line ${r.no}: no commit on ${ref} ever held ${otherPath} at ${other[2]}. Reuse the rows of a map a person merged.`);
        }
      }
    }
    if (pinCell === CONFIG.discoveryCurrent) continue;
    const drift = pinCell.match(CONFIG.discoveryDrift);
    if (drift === null) {
      report.fail(`${mapPath} line ${r.no}: the pin "${pinCell}" is not "${CONFIG.discoveryCurrent}", "drift: <12-hex> → <12-hex>" or "drift: <12-hex> → removed".`);
    } else if (drift[2] !== undefined && pathOk && filesRead !== null && !readPaths.has(path)) {
      report.fail(`${mapPath} line ${r.no}: ${path} drifted to ${drift[2]} since ${mapCell}, and the "${filesSpec.title}" table does not list it: a file that moved is read again. Read the file and add its row.`);
    }
  }

  // Each spoke path the design cites is a read in the map.
  if (filesRead !== null) {
    for (const c of design.citedPaths.filter((x) => !readPaths.has(x.path))) {
      report.fail(`${design.path} line ${c.no} cites ${c.cite}, and ${mapPath} does not list ${c.path} under "${filesSpec.title}": a citation needs a read at this commit. Read the file and add its row.`);
    }
  }
}

/* -------------------------------------------------------------- gate results */

// A note is a fact the reader should see that does not decide eligibility: it is
// printed under its gate, pass or fail, and never changes the exit code.
const gates = [];
function gate(name) {
  const g = { name, failures: [], notes: [] };
  gates.push(g);
  return { fail: (msg) => g.failures.push(msg), note: (msg) => g.notes.push(msg) };
}

/* ------------------------------------------------------- non-content masking */

// A fence opener or closer: up to three spaces, then three or more backticks or
// tildes. A backtick fence's info string may carry no backtick; a closer carries
// nothing at all.
const FENCE = /^( {0,3})(`{3,}|~{3,})(.*)$/;
// The HTML blocks whose contents a renderer shows as raw text rather than reading
// as markdown. A table inside one of these is characters on a page, not a table.
const RAW_TEXT_HTML = /^ {0,3}<(pre|script|style|textarea)(?:[\s/>]|$)/i;
const LIST_ITEM = /^( *)([-*+]|\d{1,9}[.)])( +|$)/;
const ATX_HEADING = /^ {0,3}#{1,6}(?:\s|$)/;
const THEMATIC_BREAK = /^ {0,3}(?:(?:-[ \t]*){3,}|(?:_[ \t]*){3,}|(?:\*[ \t]*){3,})$/;
// A comment that OPENS a line opens an HTML block, and an HTML block ends with the
// LINE that closes it, not with the closing marker. Text sitting after `-->` on
// that line is still inside the block, so it is raw HTML and never a heading --
// which is the difference between `-->## z` truncating a section and doing nothing.
const COMMENT_BLOCK = { '<!--': '-->', '{/*': '*/}' };
const COMMENT_BLOCK_OPEN = /^ {0,3}(<!--|\{\/\*)/;
// A link reference definition renders as NOTHING at all, and its title may run
// over as many lines as it likes, which makes it a carrier for a whole readiness
// block that no reader can see.
const LINK_DEF = /^ {0,3}\[(?:[^\]\\]|\\.)*\]:(.*)$/;
const TITLE_CLOSER = { '"': '"', "'": "'", '(': ')' };

function indentWidth(line) {
  let width = 0;
  for (const ch of line) {
    if (ch === ' ') width += 1;
    else if (ch === '\t') width += 4 - (width % 4);
    else break;
  }
  return width;
}

// COMPLETE spans only. An unterminated `<!--` in the middle of a line is not a
// comment: CommonMark prints it as text, so the gate has to read the rest of the
// line as text too. Treating it as an open region is how a review that quotes
// `<!--` in a code span loses its own verdict to a comment that is not there.
function stripInlineComments(line) {
  let text = line;
  for (const [open, close] of Object.entries(COMMENT_BLOCK)) {
    for (;;) {
      const start = text.indexOf(open);
      if (start === -1) break;
      const end = text.indexOf(close, start + open.length);
      if (end === -1) break;
      text = text.slice(0, start) + text.slice(end + close.length);
    }
  }
  return text;
}

// Everything after the destination of a link reference definition: the title, or
// null when no title has started on this line and one may begin on the next.
function linkDefTitle(line) {
  const m = line.match(LINK_DEF);
  let rest = m[1].trim();
  if (rest === '') return null;
  if (rest.startsWith('<')) {
    const gt = rest.indexOf('>');
    rest = gt === -1 ? '' : rest.slice(gt + 1).trim();
  } else {
    const sp = rest.search(/\s/);
    rest = sp === -1 ? '' : rest.slice(sp).trim();
  }
  return rest === '' ? null : rest;
}

// Blank every region of the document a reader does not read as document content,
// and return the lines. Non-content is: fenced code blocks (backtick or tilde, any
// length, with or without an info string, closed or running to end of file),
// indented code blocks, HTML comment blocks, MDX comment blocks, the raw-text HTML
// blocks, and link reference definitions with their titles.
//
// Masking, not deleting. Every line keeps its position, so every failure message
// still points at the line the author has to open.
//
// This is applied ONCE, where text becomes lines, and every parser below then works
// on the masked array. The alternative -- teaching each parser what a fence is --
// is how one parser gets missed, and one parser is all it takes: a `## Readiness`
// inside a fence is a heading to a locator and grey example text to a reader.
//
// `blockStart` is the one piece of state that makes this more than a marker hunt.
// Indented code and link reference definitions can only BEGIN where a new block
// can begin -- neither of them interrupts a paragraph -- and both of them can begin
// straight after a heading with no blank line in between. Requiring a blank line
// was the hole: `## 5. Testing plan` followed immediately by an indented table is a
// grey code block on the page and was a testing plan to the gate.
function maskNonContent(text) {
  // CR, LF and CRLF are all line endings in CommonMark. Splitting on LF alone left
  // a lone CR gluing two lines together, so a fence opener written after one was a
  // fence to every renderer and an ordinary line to the gate.
  const lines = String(text).split(/\r\n|\n|\r/);
  const masked = [];
  let fence = null;
  let rawHtml = null;
  let commentClose = null;
  let titleClose = null;
  let titlePending = false;
  let codeIndent = -1;
  let listContent = 0;
  let blockStart = true;

  for (const line of lines) {
    if (fence) {
      const m = line.match(FENCE);
      const closes = !!m && m[2][0] === fence.char && m[2].length >= fence.length && m[3].trim() === '';
      masked.push('');
      if (closes) { fence = null; blockStart = true; }
      continue;
    }
    if (rawHtml) {
      masked.push('');
      if (new RegExp(`</\\s*${rawHtml}\\s*>`, 'i').test(line)) { rawHtml = null; blockStart = true; }
      continue;
    }
    if (commentClose) {
      masked.push('');
      if (line.includes(commentClose)) { commentClose = null; blockStart = true; }
      continue;
    }
    if (titleClose) {
      masked.push('');
      if (line.includes(titleClose)) { titleClose = null; blockStart = true; }
      continue;
    }
    if (codeIndent >= 0) {
      if (line.trim() === '' || indentWidth(line) >= codeIndent) { masked.push(''); continue; }
      codeIndent = -1;
    }
    if (titlePending) {
      titlePending = false;
      const trimmed = line.trim();
      const closer = TITLE_CLOSER[trimmed[0]];
      if (closer) {
        masked.push('');
        if (trimmed.indexOf(closer, 1) === -1) titleClose = closer;
        else blockStart = true;
        continue;
      }
    }
    if (line.trim() === '') { masked.push(line); blockStart = true; continue; }

    const indent = indentWidth(line);
    if (indent < listContent) listContent = 0;

    // Four spaces from the CONTAINING BLOCK's content column, not from the margin.
    // Under `- ` the item's own content starts at column two, so six spaces is a
    // code block inside the item and two is the item continuing. Exempting list
    // items altogether -- the previous rule -- made every depth of list a safe
    // place to hide a table.
    if (blockStart && indent >= listContent + 4) {
      codeIndent = listContent + 4;
      masked.push('');
      continue;
    }

    if (blockStart && LINK_DEF.test(line)) {
      const title = linkDefTitle(line);
      masked.push('');
      if (title === null) { titlePending = true; continue; }
      const closer = TITLE_CLOSER[title[0]];
      if (closer && title.indexOf(closer, 1) === -1) { titleClose = closer; continue; }
      blockStart = true;
      continue;
    }

    const opener = line.match(FENCE);
    if (opener && !(opener[2][0] === '`' && opener[3].includes('`'))) {
      fence = { char: opener[2][0], length: opener[2].length };
      masked.push('');
      continue;
    }

    const raw = line.match(RAW_TEXT_HTML);
    if (raw) {
      const tag = raw[1].toLowerCase();
      masked.push('');
      if (new RegExp(`</\\s*${tag}\\s*>`, 'i').test(line)) blockStart = true;
      else rawHtml = tag;
      continue;
    }

    const block = line.match(COMMENT_BLOCK_OPEN);
    if (block) {
      const close = COMMENT_BLOCK[block[1]];
      masked.push('');
      if (line.indexOf(close, block[0].length) === -1) commentClose = close;
      else blockStart = true;
      continue;
    }

    if (!THEMATIC_BREAK.test(line)) {
      const li = line.match(LIST_ITEM);
      if (li) listContent = indent + li[2].length + Math.min(Math.max(li[3].length, 1), 4);
    }

    masked.push(stripInlineComments(line));
    blockStart = ATX_HEADING.test(line) || THEMATIC_BREAK.test(line);
  }
  return masked;
}

/* ------------------------------------------------------------- hidden markup */

// Markup that leaves content in the document but not in front of the reader.
// `<details>` collapses its contents behind a summary line, an HTML `<table>` is
// not a markdown table so the gate reads nothing where a reader reads rows, and a
// `hidden` attribute or a `display:none` style removes an element from the page
// while leaving every byte of it in the file. Masking cannot help here -- the
// content is real -- so the gate refuses and says where.
//
// Scanned across the WHOLE of both files, not only the sections the gate parses.
// An unclosed `<details>` two sections above the readiness block collapses it just
// as thoroughly as one wrapped around it, and a review is one token plus the
// findings behind it, so there is nowhere in it this markup is harmless.
const HIDDEN_MARKUP = /<\/?\s*(details|summary|table)\b/i;
const HIDDEN_STYLE = /<([a-z][a-z0-9-]*)\b[^>]*(?:\shidden(?=[\s/>=])|style\s*=\s*(?:"[^"]*|'[^']*)(?:display\s*:\s*none|visibility\s*:\s*hidden))/i;

// A code span is text about markup, not markup. `` `<table>` `` in a criterion is
// printed as characters by every renderer, so a design for something that emits
// HTML can state its own criteria. An UNQUOTED `<details>` in the same sentence is
// a real open tag that collapses the rest of the cell, and is still refused.
function withoutCodeSpans(line) {
  let out = '';
  let i = 0;
  while (i < line.length) {
    if (line[i] !== '`') { out += line[i]; i += 1; continue; }
    let run = 0;
    while (line[i + run] === '`') run += 1;
    const marker = '`'.repeat(run);
    const end = line.indexOf(marker, i + run);
    if (end === -1) { out += marker; i += run; continue; }
    out += ' ';
    i = end + run;
  }
  return out;
}

function findHiddenMarkup(line) {
  const visible = withoutCodeSpans(line);
  const tag = visible.match(HIDDEN_MARKUP);
  if (tag) return `<${tag[1].toLowerCase()}>`;
  const styled = visible.match(HIDDEN_STYLE);
  if (styled) return `a hidden <${styled[1].toLowerCase()}>`;
  return null;
}

function rejectHiddenMarkup(lines, path, report) {
  for (let i = 0; i < lines.length; i += 1) {
    const found = findHiddenMarkup(lines[i]);
    if (found) {
      report.fail(`${path} carries HTML ${found} markup (line ${i + 1}); the gate reads what the page shows, and this markup puts content somewhere the page does not show it. Write the document as markdown at the top level, and put HTML you are describing in backticks.`);
      return;
    }
  }
}

/* ------------------------------------------------------------------- parsers */

// Pure-token parse. Counts occurrences across the WHOLE document so that a value
// restated in prose or in a summary table is a duplicate, not a convenience.
function parseReadiness(lines, sectionRange, report) {
  const values = {};
  for (const field of READINESS) {
    const re = new RegExp(`^${field.label}:[ \\t]*(.*)$`);
    const hits = [];
    lines.forEach((line, i) => {
      const m = line.match(re);
      if (m) hits.push({ index: i, raw: m[1] });
    });
    if (hits.length === 0) {
      report.fail(`readiness field missing: "${field.label}"`);
      continue;
    }
    if (hits.length > 1) {
      report.fail(`readiness field "${field.label}" appears ${hits.length} times (lines ${hits.map((h) => h.index + 1).join(', ')}); must appear exactly once`);
      continue;
    }
    const hit = hits[0];
    if (!sectionRange || hit.index < sectionRange[0] || hit.index > sectionRange[1]) {
      report.fail(`readiness field "${field.label}" (line ${hit.index + 1}) is outside the "## Readiness" section`);
      continue;
    }
    if (!field.accept.test(hit.raw)) {
      report.fail(`readiness field "${field.label}" value "${hit.raw}" is not a pure token matching ${field.accept}`);
      continue;
    }
    values[field.label] = hit.raw;
    if (!field.require(hit.raw)) {
      report.fail(`readiness field "${field.label}" is "${hit.raw}"; gate requires otherwise`);
    }
  }
  return values;
}

// A heading is a LOCATOR, not a token, so an optional section number is tolerated:
// "## Readiness" and "## 8. Readiness" both locate the same section. That is the
// only tolerated variation in this file -- field labels and field VALUES are still
// matched literally and are never normalised.
//
// A section ends at the next `#` or `##` heading. A DEEPER heading does not end it,
// because a reader does not end it there either: `### Out of scope` under section 4
// is still section 4 on the page. Ending at any heading of any level was worse than
// the problem it fixed -- an ordinary visible sub-heading then carried an open
// blocking clarification out of the gate's sight while leaving it in the reader's.
// What that change was really trying to fix is a sub-table being read as more rows
// of the section's table, and that is fixed in tableBlocks() instead.
const SECTION_END = /^#{1,2}\s/;
const HEADING = /^ {0,3}#{1,6}\s/;

function sectionRanges(lines, heading) {
  const re = new RegExp(`^##\\s+(?:\\d+\\.\\s+)?${heading}\\s*$`);
  const starts = [];
  lines.forEach((line, i) => { if (re.test(line)) starts.push(i); });
  return starts.map((start) => {
    let end = lines.length - 1;
    for (let i = start + 1; i < lines.length; i += 1) {
      if (SECTION_END.test(lines[i])) { end = i - 1; break; }
    }
    return [start, end];
  });
}

// The gate reads the first section of a given name. A second one is therefore
// content nobody checks, and which of the two is read is decided by their order --
// so it fails rather than being silently preferred.
function sectionRange(lines, heading, report) {
  const all = sectionRanges(lines, heading);
  if (all.length > 1 && report) {
    report.fail(`"## ${heading}" appears ${all.length} times (lines ${all.map((r) => r[0] + 1).join(', ')}); one section, once, or the gate is reading one and the reader another`);
  }
  return all.length ? all[0] : null;
}

// One row is one line. A literal pipe inside a cell is escaped as `\|`, the rule
// CLAR-log.template.md states as the schema of record: the split ignores escaped
// pipes and each cell is unescaped afterwards, so a cell may carry a pipe without
// changing the cell count. A row whose terminating pipe is itself escaped has no
// terminator and is malformed, which fails the gate rather than being repaired.
//
// Characters with no width are removed before a cell is measured. `String.trim()`
// strips a non-breaking space but not a zero-width one, so a cell holding a single
// U+200B is a blank cell to a reader and a one-character value to a falsiness test
// -- which is an empty criterion and an unnamed test that both pass.
const INVISIBLE = /[\u200B-\u200F\u202A-\u202E\u2060\uFEFF\u00AD]/g;

function splitRow(line) {
  const trimmed = line.replace(INVISIBLE, '').trim();
  if (!trimmed.startsWith('|') || !trimmed.endsWith('|')) return null;
  if (/(?:^|[^\\])(?:\\\\)*\\$/.test(trimmed.slice(0, -1))) return null;
  return trimmed
    .slice(1, -1)
    .split(/(?<!\\)\|/)
    .map((c) => c.trim().replace(/\\\|/g, '|'));
}

// A cell that names nothing. A dash or a TBD in the criterion or test-name column
// is the cheapest way to satisfy the criterion-to-test map without writing either,
// so the gate rejects it exactly as it rejects an empty cell.
//
// Three tests, because a placeholder survives being decorated. A cell that is
// wholly angle-bracketed is the design template's own authoring guidance --
// `<observable, testable statement>`, `<test_module::<test_name>>` -- and left in
// place the untouched template is a design that passes all four gates with no
// content in it. A cell with no letter and no digit names nothing whatever it is
// made of. And one character is an initial, not a criterion.
//
// The angle-bracket test needs the WHOLE cell to be bracketed, so a real criterion
// mentioning `> 1MB` or `<Foo>` inside a sentence is unaffected.
function isPlaceholder(cell) {
  const value = cell.trim();
  if (value === '') return false;
  if (value.startsWith('<') && value.endsWith('>')) return true;
  let token = value;
  let last;
  do {
    last = token;
    token = token
      .replace(/^[("'`“‘\[]+/, '')
      .replace(/[)"'`”’\]]+$/, '')
      .replace(/[.,;:!?…]+$/, '')
      .trim();
  } while (token !== last);
  const compact = token.replace(/\s+/g, '').toLowerCase();
  if (CONFIG.placeholderToken.test(compact)) return true;
  if (!/[a-z0-9]/i.test(compact)) return true;
  return compact.length < 2;
}

// A line a reader reads as a table row and the parser does not collect.
const UNREADABLE_ROW = /^\s*>[\s>]*\|.*\|\s*$/;

// Checked in every parsed section, whether or not a table was also found. Guarded
// behind "the parser found no rows at all" it was trivially defeated: keep one real
// row so the table is non-empty, and blockquote the incriminating one beside it.
function rejectUnreadableRows(lines, range, sectionName, report) {
  for (let i = range[0] + 1; i <= range[1]; i += 1) {
    if (UNREADABLE_ROW.test(lines[i])) {
      report.fail(`the "${sectionName}" section carries a row the gate cannot read (line ${i + 1}); every row is a markdown row at the top level of the section, never blockquoted and never indented into another block`);
      return true;
    }
  }
  return false;
}

// A markdown table is a BLOCK: a run of row-shaped lines that starts where a block
// can start. A run that starts in the middle of a paragraph is not a table to a
// renderer -- the pipes are printed as text -- so it is not one here either.
//
// Runs are kept apart rather than pooled. Pooling them is what made a sub-table
// under a sub-heading look like more rows of the section's real table, and ending
// the section at the sub-heading to avoid that opened a much larger hole. Here the
// section keeps its full extent and the runs stay distinguishable.
function tableBlocks(lines, range) {
  const blocks = [];
  let current = null;
  for (let i = range[0] + 1; i <= range[1]; i += 1) {
    const isRow = lines[i].replace(INVISIBLE, '').trim().startsWith('|');
    if (!isRow) { current = null; continue; }
    if (!current) {
      const before = i === 0 ? '' : lines[i - 1];
      current = {
        opensBlock: i === range[0] + 1 || before.trim() === '' || HEADING.test(before),
        rows: [],
      };
      blocks.push(current);
    }
    current.rows.push({ line: lines[i], no: i + 1 });
  }
  return blocks;
}

// The one run in the section whose first row is the header the gate reads. Other
// runs are other content -- an out-of-scope list, a glossary -- and are left alone,
// EXCEPT that a row outside the table carrying an identifier in the gate's own
// namespace is a row pretending not to be one. Two runs carrying the same header
// is not a table with an appendix, it is two tables, and which one the gate reads
// must not be decided by their order.
function selectTable(blocks, isHeader, idPattern, sectionName, expected, report) {
  const matches = blocks.filter((b) => isHeader(splitRow(b.rows[0].line)));
  if (matches.length > 1) {
    report.fail(`the "${sectionName}" section carries ${matches.length} tables with the same header (lines ${matches.map((b) => b.rows[0].no).join(', ')}); one table, once, or the gate reads one and the reader another`);
    return null;
  }
  if (matches.length === 0) {
    report.fail(`the "${sectionName}" table header (line ${blocks[0].rows[0].no}) must begin "${expected}"`);
    return null;
  }
  const chosen = matches[0];
  for (const block of blocks) {
    if (block === chosen) continue;
    for (const entry of block.rows) {
      const cells = splitRow(entry.line);
      if (cells && idPattern.test(cells[0])) {
        report.fail(`the "${sectionName}" section carries a row identified "${cells[0]}" (line ${entry.no}) that is not in the table the gate reads; a row separated from the table by a blank line, a heading or a masked region is not part of it to a renderer either`);
      }
    }
  }
  if (!chosen.opensBlock) {
    report.fail(`the "${sectionName}" table (line ${chosen.rows[0].no}) does not start a block, so a renderer prints its pipes as text instead of drawing a table; leave a blank line above the header row`);
    return null;
  }
  return chosen;
}

// Section 4. The criterion set is DERIVED here. A row inside the table that does
// not carry an AC-<n> identifier fails; it is never skipped, because a skipped
// row is a criterion that quietly stops needing a test. `carried` receives each
// criterion's line and requirement id -- the id null where the cell was refused
// here, so the trace against the work item does not report one defect twice.
function parseCriteria(lines, range, report, carried = new Map()) {
  if (!range) {
    report.fail(`no "## ${CONFIG.acSection}" section in the design document`);
    return null;
  }
  if (rejectUnreadableRows(lines, range, CONFIG.acSection, report)) return null;
  const blocks = tableBlocks(lines, range);
  if (blocks.length === 0) {
    report.fail(`the "${CONFIG.acSection}" section (line ${range[0] + 1}) has no criterion table: expected a header, a separator and at least one AC-<n> row`);
    return null;
  }
  // Both column names, not just the first. The gate reads the criterion out of
  // column two by position, so a table whose second column is something else --
  // or which has no criterion column at all -- hands the checks a cell that was
  // never the criterion, and the placeholder in the real column is never seen.
  const table = selectTable(
    blocks,
    (h) => !!h && h.length >= 2 && h[0] === 'ID' && h[1] === 'Criterion',
    CONFIG.acIdLoose, CONFIG.acSection, '| ID | Criterion |', report,
  );
  if (!table) return null;
  const rows = table.rows;
  const header = splitRow(rows[0].line);
  if (rows.length < 3) {
    report.fail(`the "${CONFIG.acSection}" table (line ${rows[0].no}) has no rows: expected a header, a separator and at least one AC-<n> row`);
    return null;
  }
  if (!isSeparatorRow(splitRow(rows[1].line), header.length)) {
    report.fail(`the "${CONFIG.acSection}" table (line ${rows[1].no}) is missing a well-formed separator row`);
    return null;
  }
  // The requirement column is found by name. Absent, the requirement id stops
  // here and the validation report has nothing to repeat; present twice, the gate
  // would be reading one and the reader another.
  const reqCols = header.map((h, i) => (h === CONFIG.requirementColumn ? i : -1)).filter((i) => i >= 0);
  if (reqCols.length === 0) {
    report.fail(`the "${CONFIG.acSection}" table header (line ${rows[0].no}) has no "${CONFIG.requirementColumn}" column; every criterion names the requirement criterion it carries, ${CONFIG.requirementForms}, and that column is how the requirement reaches the validation report`);
  } else if (reqCols.length > 1) {
    report.fail(`the "${CONFIG.acSection}" table header (line ${rows[0].no}) carries ${reqCols.length} "${CONFIG.requirementColumn}" columns; one column, once, or the gate reads one and the reader another`);
  }
  const reqCol = reqCols.length === 1 ? reqCols[0] : -1;
  const ids = [];
  for (const entry of rows.slice(2)) {
    const cells = splitRow(entry.line);
    if (!cells || cells.length !== header.length) {
      report.fail(`acceptance-criteria row (line ${entry.no}) is malformed: expected ${header.length} cells, found ${cells ? cells.length : 0}`);
      continue;
    }
    if (!CONFIG.acIdPattern.test(cells[0])) {
      report.fail(`acceptance-criteria row (line ${entry.no}) identifier "${cells[0]}" does not match AC-<n>`);
      continue;
    }
    if (!cells[1]) {
      report.fail(`acceptance criterion ${cells[0]} (line ${entry.no}) has an empty criterion statement; the second cell is the criterion and an identifier alone is not a criterion`);
    } else if (isPlaceholder(cells[1])) {
      report.fail(`acceptance criterion ${cells[0]} (line ${entry.no}) has "${cells[1]}" as its criterion statement, which is a placeholder and not an observable, testable statement`);
    }
    // A deprecated criterion keeps its requirement: the row keeps its number, and
    // the report still has to say what became of the requirement it carried.
    let requirementId = null;
    if (reqCol >= 0) {
      const requirement = cells[reqCol];
      if (!requirement) {
        report.fail(`acceptance criterion ${cells[0]} (line ${entry.no}) has an empty "${CONFIG.requirementColumn}" cell; every criterion names the requirement criterion it carries, ${CONFIG.requirementForms}`);
      } else if (!CONFIG.requirementPattern.test(requirement)) {
        report.fail(`acceptance criterion ${cells[0]} (line ${entry.no}) names requirement "${requirement}", which is not one ${CONFIG.requirementForms}; one requirement criterion per row, no leading zeros, nothing else in the cell`);
      } else {
        requirementId = requirement;
      }
    }
    if (ids.includes(cells[0])) {
      report.fail(`acceptance criterion ${cells[0]} is defined twice (line ${entry.no}); identifiers are unique and are never reused`);
      continue;
    }
    ids.push(cells[0]);
    carried.set(cells[0], { requirement: requirementId, no: entry.no });
  }
  if (ids.length === 0) report.fail(`the "${CONFIG.acSection}" table defines no AC-<n> rows`);
  return ids;
}

// The work item's criteria, read as check-decomposition.js reads them: the
// `| ID | Criterion |` table under "## Acceptance criteria", the Carries column
// found by name. Returns a map from each AC-<n> to the requirement id it
// carries, or null where no criterion can be read. Every reason the table
// cannot be traced is a finding: a design is only as traced as the work item
// it is checked against is readable. The slug the item sits under decides the
// one form its Carries cells may take: under the ticket slug, the ticket's own
// criteria, `JIRA-<key>.AC-<m>`; anywhere else, a requirements document's.
function parseWorkItem(lines, path, key, report) {
  const fromTicket = path.split('/')[CONFIG.backlogDir.split('/').length] === CONFIG.ticketSlug;
  const ticketPrefix = `JIRA-${key}.AC-`;
  const carriesForm = fromTicket ? `${ticketPrefix}<m>` : 'REQ-<n>.AC-<m>';
  const isCarries = (cell) => (fromTicket
    ? cell.startsWith(ticketPrefix) && cell.slice(ticketPrefix.length).search(/^[1-9]\d*$/) === 0
    : cell.search(CONFIG.documentCriterion) === 0);
  const at = { fail: (msg) => report.fail(`trace check failed: ${path}: ${msg}`) };
  const range = sectionRange(lines, CONFIG.acSection, at);
  if (!range) {
    at.fail(`no "## ${CONFIG.acSection}" section. The work item's criteria are read from it`);
    return null;
  }
  if (rejectUnreadableRows(lines, range, CONFIG.acSection, at)) return null;
  const blocks = tableBlocks(lines, range);
  if (blocks.length === 0) {
    at.fail(`the "${CONFIG.acSection}" section (line ${range[0] + 1}) has no criteria table`);
    return null;
  }
  const table = selectTable(
    blocks,
    (h) => !!h && h.length >= 2 && h[0] === 'ID' && h[1] === 'Criterion',
    CONFIG.acIdLoose, CONFIG.acSection, '| ID | Criterion |', at,
  );
  if (!table) return null;
  const header = splitRow(table.rows[0].line);
  if (table.rows.length < 2 || !isSeparatorRow(splitRow(table.rows[1].line), header.length)) {
    at.fail(`the "${CONFIG.acSection}" table (line ${table.rows[0].no}) is missing a well-formed separator row`);
    return null;
  }
  const cols = header.map((h, i) => (h === CONFIG.carriesColumn ? i : -1)).filter((i) => i >= 0);
  if (cols.length !== 1) {
    at.fail(`the "${CONFIG.acSection}" table (line ${table.rows[0].no}) has ${cols.length} "${CONFIG.carriesColumn}" columns, not one. Each criterion names its requirement id there`);
  }
  const criteria = new Map();
  for (const entry of table.rows.slice(2)) {
    const cells = splitRow(entry.line);
    if (!cells || cells.length !== header.length || !CONFIG.acIdPattern.test(cells[0]) || criteria.has(cells[0])) continue;
    let carries = null;
    if (cols.length === 1) {
      if (isCarries(cells[cols[0]])) {
        carries = cells[cols[0]];
      } else {
        at.fail(`line ${entry.no}: ${cells[0]} carries "${cells[cols[0]]}", which is not one ${carriesForm}${fromTicket ? `; a story under ${CONFIG.backlogDir}/${CONFIG.ticketSlug}/ carries the criteria of its own ticket` : ''}`);
      }
    }
    criteria.set(cells[0], carries);
  }
  if (criteria.size === 0) {
    at.fail(`the "${CONFIG.acSection}" table (line ${table.rows[0].no}) defines no AC-<n> row`);
    return null;
  }
  return criteria;
}

// Every pipe table on a page. GitHub drops the cells of a row past its header's
// count and pads a short row, so a row whose count is not the header's hides text
// or holds a gap that a reader cannot see (PLDC-686). GitHub renders a table under
// a paragraph line too, so a block counts wherever it starts. A block with no
// separator row of the header's width renders as text, and is skipped. Not seen:
// a row with no leading pipe, and a table inside a blockquote.
function rejectMalformedRows(lines, path, report) {
  for (const block of tableBlocks(lines, [-1, lines.length - 1])) {
    if (block.rows.length < 2) continue;
    const header = splitRow(block.rows[0].line);
    if (!header || !isSeparatorRow(splitRow(block.rows[1].line), header.length)) continue;
    for (const entry of block.rows.slice(2)) {
      const cells = splitRow(entry.line);
      if (!cells) {
        report.fail(`${path} line ${entry.no}: the table row does not end with an unescaped |, so its cells cannot be counted against its header (line ${block.rows[0].no}); end the row with |, and write a literal pipe in a cell as \\|`);
      } else if (cells.length !== header.length) {
        report.fail(`${path} line ${entry.no}: the table row has ${cells.length} cells and its header (line ${block.rows[0].no}) has ${header.length}; write one row on one line, and a literal pipe in a cell as \\|`);
      }
    }
  }
}

function isSeparatorRow(cells, width) {
  return !!cells && cells.length === width && cells.every((c) => /^:?-{2,}:?$/.test(c));
}

// Section 5. The covered set is DERIVED here, and every row must name a test.
// A criterion listed against an empty cell -- or against a dash, a TBD or any
// other placeholder -- is not covered. Accepting a placeholder here would turn
// the derived criterion-to-test map back into an attestation one column over.
function parseTestingPlan(lines, range, report) {
  if (!range) {
    report.fail(`no "## ${CONFIG.testSection}" section in the design document`);
    return null;
  }
  if (rejectUnreadableRows(lines, range, CONFIG.testSection, report)) return null;
  const blocks = tableBlocks(lines, range);
  if (blocks.length === 0) {
    report.fail(`the "${CONFIG.testSection}" section (line ${range[0] + 1}) has no test table: expected a header, a separator and at least one AC-<n> row`);
    return null;
  }
  // As in section 4: the test name is read out of column two by position, so the
  // column must be the one the template names.
  const table = selectTable(
    blocks,
    (h) => !!h && h.length >= 2 && h[0] === 'AC' && h[1] === 'Test name',
    CONFIG.acIdLoose, CONFIG.testSection, '| AC | Test name |', report,
  );
  if (!table) return null;
  const rows = table.rows;
  const header = splitRow(rows[0].line);
  if (rows.length < 3) {
    report.fail(`the "${CONFIG.testSection}" table (line ${rows[0].no}) has no rows: expected a header, a separator and at least one AC-<n> row`);
    return null;
  }
  if (!isSeparatorRow(splitRow(rows[1].line), header.length)) {
    report.fail(`the "${CONFIG.testSection}" table (line ${rows[1].no}) is missing a well-formed separator row`);
    return null;
  }
  const covered = [];
  for (const entry of rows.slice(2)) {
    const cells = splitRow(entry.line);
    if (!cells || cells.length !== header.length) {
      report.fail(`testing-plan row (line ${entry.no}) is malformed: expected ${header.length} cells, found ${cells ? cells.length : 0}`);
      continue;
    }
    if (!CONFIG.acIdPattern.test(cells[0])) {
      report.fail(`testing-plan row (line ${entry.no}) criterion "${cells[0]}" does not match AC-<n>`);
      continue;
    }
    if (!cells[1]) {
      report.fail(`testing-plan row (line ${entry.no}) for ${cells[0]} has an empty test name; a criterion without a named test is not covered`);
      continue;
    }
    if (isPlaceholder(cells[1])) {
      report.fail(`testing-plan row (line ${entry.no}) for ${cells[0]} has "${cells[1]}" in the test-name column, which is a placeholder and not a named test; a criterion without a named test is not covered`);
      continue;
    }
    if (covered.includes(cells[0])) {
      report.fail(`testing-plan row (line ${entry.no}) covers ${cells[0]} a second time; every criterion appears exactly once`);
      continue;
    }
    covered.push(cells[0]);
  }
  return covered;
}

// A Closed row is released by its date, so the date has to be one. A shape check
// passes 0000-00-00 and 9999-99-99, and a date that has not happened yet is not
// evidence that an answer landed.
function isResolvedDate(value) {
  const m = CONFIG.clarResolvedDate.exec(value);
  if (!m) return false;
  const [year, month, day] = value.split('-').map(Number);
  const date = new Date(Date.UTC(year, month - 1, day));
  if (date.getUTCFullYear() !== year || date.getUTCMonth() !== month - 1 || date.getUTCDate() !== day) return false;
  return date.getTime() <= Date.now() + 24 * 60 * 60 * 1000;
}

// Strict schema. A row that does not parse FAILS. It is never skipped, because a
// skipped malformed row is how a blocking clarification becomes invisible.
function parseClarTable(lines, range, report) {
  const rows = [];
  if (!range) {
    report.fail('no "## Clarifications" section in the design document');
    return rows;
  }
  // NONE is the escape for a design with no clarifications, so it has to mean
  // exactly that. A section carrying rows the gate cannot read -- blockquoted, or
  // in any other shape that is a table to a reader and not to the parser -- is not
  // a section whose visible rows are the whole log, whatever stands beside them.
  if (rejectUnreadableRows(lines, range, 'Clarifications', report)) return rows;

  const body = lines.slice(range[0] + 1, range[1] + 1);
  const blocks = tableBlocks(lines, range);
  if (blocks.length === 0) {
    // Anchored, like every other token in this file: NONE at the start of its own
    // line, in the document a reader sees.
    if (body.some((l) => /^NONE\s*$/.test(l))) return rows;
    report.fail('clarification section has neither a table nor the literal token NONE');
    return rows;
  }
  const table = selectTable(
    blocks,
    (h) => !!h && h.join('|') === CONFIG.clarColumns.join('|'),
    CONFIG.clarIdLoose, 'Clarifications', CONFIG.clarColumns.map((c) => `| ${c} `).join('') + '|', report,
  );
  if (!table) return rows;
  if (!isSeparatorRow(splitRow(table.rows[1] ? table.rows[1].line : ''), CONFIG.clarColumns.length)) {
    report.fail('clarification table is missing a well-formed separator row');
    return rows;
  }
  for (const entry of table.rows.slice(2)) {
    const cells = splitRow(entry.line);
    if (!cells || cells.length !== CONFIG.clarColumns.length) {
      report.fail(`clarification row (line ${entry.no}) is malformed: expected ${CONFIG.clarColumns.length} cells, found ${cells ? cells.length : 0}`);
      continue;
    }
    const [id, question, source, blocking, routedTo, status, resolution, resolved] = cells;
    if (!CONFIG.clarIdPattern.test(id)) {
      report.fail(`clarification row (line ${entry.no}) identifier "${id}" does not match CLAR-<SYSTEM>-<section>-<nn>`);
    }
    if (!question || !source) {
      report.fail(`clarification row (line ${entry.no}) has an empty question or source`);
    }
    if (blocking !== 'yes' && blocking !== 'no') {
      report.fail(`clarification row (line ${entry.no}) Blocking must be "yes" or "no", found "${blocking}"`);
    }
    if (!CONFIG.clarStatuses.includes(status)) {
      report.fail(`clarification row (line ${entry.no}) Status must be one of ${CONFIG.clarStatuses.join('/')}, found "${status}"`);
    }
    if (CONFIG.clarRoutingStatuses.includes(status) && !routedTo) {
      report.fail(`clarification row (line ${entry.no}) is ${status} with no routing target`);
    }
    if ((status === 'Answered' || status === 'Closed') && !resolution) {
      report.fail(`clarification row (line ${entry.no}) is ${status} with an empty resolution`);
    }
    // `Closed` is the release bar, so the date the answer landed is critical
    // and is checked. Earlier statuses may legitimately carry an empty Resolved.
    if (status === 'Closed' && !isResolvedDate(resolved)) {
      report.fail(`clarification row (line ${entry.no}) is Closed with Resolved "${resolved}"; Closed requires a YYYY-MM-DD date that exists and has passed`);
    }
    if (blocking === 'yes' && CONFIG.clarOpenStatuses.includes(status)) {
      report.fail(`clarification row (line ${entry.no}) is blocking and still ${status}; a blocking row releases only at Closed or Withdrawn`);
    }
    rows.push({ id, blocking, status });
  }
  return rows;
}

/* ---------------------------------------------------------------------- main */

function main() {
  const key = process.argv[2];
  if (!key || !CONFIG.keyPattern.test(key)) {
    // Derived, not hard-coded: on a repository that is not { "type": "module" }
    // this file is installed as check-dev-ready.mjs, and a usage line naming the
    // other extension sends the reader to a file that is not there.
    const invoked = process.argv[1] || 'scripts/check-dev-ready.js';
    process.stderr.write(`usage: node ${invoked} <WORK-ITEM-KEY>   e.g. PROJ-412\n`);
    process.exit(EXIT.USAGE);
  }

  // The repository that is asking, when the gate is run from another
  // repository's CI. Empty is the same as unset: the hub asking about its own
  // designs names nobody. A value that is set and not a repository id is a
  // caller error, not a finding about the design.
  const asking = (process.env.HARNESS_REPO || '').trim() || null;
  if (asking !== null && !CONFIG.repositoryPattern.test(asking)) {
    process.stderr.write(`usage: HARNESS_REPO must be a repository id (letters, digits, ".", "_", "-"), got "${asking}"\n`);
    process.exit(EXIT.USAGE);
  }

  const ref = syncDefaultBranch();
  const tracked = listTree(ref, CONFIG.designDir);
  const named = (suffix) => tracked.filter((e) => {
    const base = e.path.slice(e.path.lastIndexOf('/') + 1);
    return base.startsWith(`${key}.`) && base.endsWith(suffix);
  });

  // Gate 1 -- exactly one readable design document on the default branch, and it
  // says which work item it is for.
  const g1 = gate('design document');
  // The ids on the design's Context: line, once the line is read without a
  // failure: what gate 3 compares the work item's line against.
  let designContext = null;
  const designs = named(CONFIG.designSuffix).filter((e) => !e.path.endsWith(CONFIG.reviewSuffix));
  if (designs.length !== 1) {
    g1.fail(`expected exactly one "*${CONFIG.designSuffix}" for ${key} on ${ref}, found ${designs.length}${designs.length ? `: ${designs.map((e) => e.path).join(', ')}` : ''}`);
  }
  const designText = designs.length === 1 ? readArtefact(ref, designs[0], g1, 'design document') : null;
  const designLines = designText === null ? null : maskNonContent(designText);
  if (designLines !== null) {
    rejectHiddenMarkup(designLines, designs[0].path, g1);
    rejectMalformedRows(designLines, designs[0].path, g1);
    // A design is bound to its work item by what it says, not by what it is
    // called. Without this the key selects a filename and nothing more, so a
    // renamed design carries a review of different work. EVERY such line is
    // checked, not just one of them: an appendix naming the right key does not
    // make a Traceability section naming the wrong one correct.
    const identity = new RegExp(`^(?:${CONFIG.identityLabels.join('|')}):[ \\t]*(\\S.*?)\\s*$`);
    const claims = [];
    designLines.forEach((line, i) => {
      const m = line.match(identity);
      if (m) claims.push({ no: i + 1, value: m[1] });
    });
    if (!claims.some((c) => c.value === key)) {
      g1.fail(`${designs[0].path} never names ${key} on a line of its own: expected "${CONFIG.identityLabels[0]}: ${key}"`);
    }
    const wrong = claims.filter((c) => c.value !== key);
    if (wrong.length) {
      g1.fail(`${designs[0].path} carries a "${CONFIG.identityLabels[0]}:" line naming ${wrong.map((c) => `"${c.value}" (line ${c.no})`).join(', ')}; a design is evidence about one work item, and that item is ${key}`);
    }
    // A design is also bound to the repository its code lands in. Without this
    // line a design written for one repository passes for any other, because
    // nothing in the four gates reads code and nothing else names a repository.
    // Exactly one line, a well-formed id, and -- when another repository's CI is
    // asking -- the same id. The gate does not check that the repository exists;
    // it reads one remote, and that remote is the one holding the design.
    const repoLine = new RegExp(`^${CONFIG.repositoryLabel}:[ \\t]*(\\S.*?)\\s*$`);
    const repos = [];
    designLines.forEach((line, i) => {
      const m = line.match(repoLine);
      if (m) repos.push({ no: i + 1, value: m[1] });
    });
    if (repos.length === 0) {
      g1.fail(`${designs[0].path} never says which repository its code lands in: expected exactly one "${CONFIG.repositoryLabel}: <repository-id>" line`);
    } else if (repos.length > 1) {
      g1.fail(`${designs[0].path} carries ${repos.length} "${CONFIG.repositoryLabel}:" lines (${repos.map((r) => `"${r.value}" on line ${r.no}`).join(', ')}); a design lands in exactly one repository`);
    } else {
      const repo = repos[0].value;
      if (isPlaceholder(repo) || !CONFIG.repositoryPattern.test(repo)) {
        g1.fail(`${designs[0].path} line ${repos[0].no}: "${CONFIG.repositoryLabel}: ${repo}" is not a repository id; expected the repository's bare name (letters, digits, ".", "_", "-")`);
      } else if (asking !== null && repo !== asking) {
        g1.fail(`this design is written for "${repo}"; "${asking}" is asking`);
      }
    }
    // A design is also bound to the repository's own rules it was written under.
    // Without this line a design that read no rules is indistinguishable from one
    // written for a repository that declares none, and the sprint cannot tell
    // whether the rules have moved since. Exactly one line: the literal `none`, or
    // the folder cited at a commit, with the id the design's own `Repository:`.
    const rulesLine = new RegExp(`^${CONFIG.rulesLabel}:[ \\t]*(\\S.*?)\\s*$`);
    const rulesClaims = [];
    designLines.forEach((line, i) => {
      const m = line.match(rulesLine);
      if (m) rulesClaims.push({ no: i + 1, value: m[1] });
    });
    const expected = `"${CONFIG.rulesLabel}: ${CONFIG.rulesNone}" or "${CONFIG.rulesLabel}: <repository-id>@<12-hex>:<path>"`;
    if (rulesClaims.length === 0) {
      g1.fail(`${designs[0].path} never says which rules it was written under: expected exactly one ${expected} line`);
    } else if (rulesClaims.length > 1) {
      g1.fail(`${designs[0].path} carries ${rulesClaims.length} "${CONFIG.rulesLabel}:" lines (${rulesClaims.map((r) => `"${r.value}" on line ${r.no}`).join(', ')}); a design is written under one set of rules`);
    } else {
      const { value, no } = rulesClaims[0];
      const cite = value.match(CONFIG.rulesCite);
      if (value !== CONFIG.rulesNone && (isPlaceholder(value) || cite === null)) {
        g1.fail(`${designs[0].path} line ${no}: "${CONFIG.rulesLabel}: ${value}" is neither ${expected}; copy the line scripts/read-spoke-rules.mjs prints`);
      } else if (cite !== null && repos.length === 1 && CONFIG.repositoryPattern.test(repos[0].value) && cite[1] !== repos[0].value) {
        g1.fail(`${designs[0].path} line ${no}: "${CONFIG.rulesLabel}:" cites "${cite[1]}"; this design lands in "${repos[0].value}", and a design is written under its own repository's rules`);
      }
    }
    // The Prime Security guardrails the design chose, where it says. At most one
    // line, in one of the four forms; no line at all is `off`.
    const guardrailsLine = new RegExp(`^${CONFIG.guardrailsLabel}:[ \\t]*(\\S.*?)\\s*$`);
    const guardrailsClaims = [];
    designLines.forEach((line, i) => {
      const m = line.match(guardrailsLine);
      if (m) guardrailsClaims.push({ no: i + 1, value: m[1] });
    });
    if (guardrailsClaims.length > 1) {
      g1.fail(`${designs[0].path} carries ${guardrailsClaims.length} "${CONFIG.guardrailsLabel}:" lines (${guardrailsClaims.map((r) => `"${r.value}" on line ${r.no}`).join(', ')}); a design chooses its guardrails once`);
    } else if (guardrailsClaims.length === 1) {
      const { value, no } = guardrailsClaims[0];
      const cite = value.match(CONFIG.guardrailsCite);
      const ids = cite ? cite[2].split(', ') : [];
      const badIds = ids.filter((id) => id.match(CONFIG.guardrailsId) === null);
      const twice = ids.filter((id, i) => ids.indexOf(id) !== i);
      if (!CONFIG.guardrailsWords.includes(value) && cite === null) {
        g1.fail(`${designs[0].path} line ${no}: "${CONFIG.guardrailsLabel}: ${value}" is not off, none, unchecked or prime@<12-hex>:<id>, <id>; copy the line scripts/prime.mjs choose prints`);
      } else if (badIds.length) {
        g1.fail(`${designs[0].path} line ${no}: "${CONFIG.guardrailsLabel}:" names ${badIds.map((id) => `"${id}"`).join(', ')}, which ${badIds.length === 1 ? 'is not a Prime guardrail id' : 'are not Prime guardrail ids'}; ids are joined by ", " as scripts/prime.mjs choose prints them`);
      } else if (twice.length) {
        g1.fail(`${designs[0].path} line ${no}: "${CONFIG.guardrailsLabel}:" names ${[...new Set(twice)].join(', ')} more than once`);
      }
    }
    // And to the context documents it was written against. Without this line a
    // design that read none looks like one for which none bind, and nobody can
    // trace which contract or decision shaped it. Exactly one line: the literal
    // `none`, or one entry per document the script selected -- id, pin, path --
    // in the form it prints them, so a reader sees which file was read and the
    // gate sees whether that file has moved since.
    // The hub commit the design records, which its hub entries are proved
    // against below. A failed line is reported here and leaves nothing to prove
    // the pins against.
    const hubCommit = checkHubCommit(ref, designLines, designs[0].path, g1);
    const contextLine = new RegExp(`^${CONFIG.contextLabel}:[ \\t]*(\\S.*?)\\s*$`);
    const contextClaims = [];
    designLines.forEach((line, i) => {
      const m = line.match(contextLine);
      if (m) contextClaims.push({ no: i + 1, value: m[1] });
    });
    const contextExpected = `"${CONFIG.contextLabel}: ${CONFIG.contextNone}" or "${CONFIG.contextLabel}: <id>@<12-hex>:<path>${CONFIG.contextSeparator}<id>@<12-hex>:<repository-id>:<path>"`;
    if (contextClaims.length === 0) {
      g1.fail(`${designs[0].path} never says which context documents it was written against: expected exactly one ${contextExpected} line`);
    } else if (contextClaims.length > 1) {
      g1.fail(`${designs[0].path} carries ${contextClaims.length} "${CONFIG.contextLabel}:" lines (${contextClaims.map((c) => `"${c.value}" on line ${c.no}`).join(', ')}); a design is written against one set of context documents`);
    } else {
      const { value, no } = contextClaims[0];
      const items = value.split(CONFIG.contextSeparator);
      const entries = items.map((item) => {
        const m = item.match(CONFIG.contextEntry);
        if (m) return { item, id: m[1], pin: m[2], repository: m[3] || null, path: m[4] };
        return CONFIG.contextId.test(item) ? { item, id: item, pin: null } : null;
      });
      const oldStd = items.map((item) => item.match(CONFIG.contextOldStd)).filter(Boolean).map((m) => m[1]);
      const bad = items.filter((item, i) => entries[i] === null && !item.match(CONFIG.contextOldStd));
      const ids = entries.filter(Boolean).map((e) => e.id);
      const repeated = ids.filter((id, i) => ids.indexOf(id) !== i);
      const pinned = entries.filter((e) => e !== null && e.pin !== null);
      const bare = entries.filter((e) => e !== null && e.pin === null);
      const at = `${designs[0].path} line ${no}: "${CONFIG.contextLabel}: ${value}"`;
      let globalTexts = new Map();
      const alwaysOnIds = new Set();
      if (value === CONFIG.contextNone) {
        // Nothing binds, said in the one form the script prints it.
        designContext = new Set();
      } else if (oldStd.length) {
        g1.fail(`${at} names ${oldStd.map((id) => `"${id}"`).join(', ')}, a standard by number, the form before standards were named std-<topic>; re-run scripts/read-context.mjs for the design's paths, copy the line it prints, and have the design re-reviewed`);
      } else if (isPlaceholder(value) || bad.length) {
        g1.fail(`${at} is neither ${contextExpected}${bad.length && !isPlaceholder(value) ? `: ${bad.map((b) => JSON.stringify(b)).join(', ')} ${bad.length === 1 ? 'is not a context entry' : 'are not context entries'}` : ''}; copy the line scripts/read-context.mjs prints`);
      } else if (ids.includes(CONFIG.contextNone)) {
        g1.fail(`${at} lists "${CONFIG.contextNone}" beside document ids; "${CONFIG.contextNone}" stands alone, and means no document binds`);
      } else if (repeated.length) {
        g1.fail(`${at} names ${[...new Set(repeated)].map((r) => `"${r}"`).join(', ')} more than once; copy the line scripts/read-context.mjs prints`);
      } else if (pinned.length && bare.length) {
        g1.fail(`${at} mixes entries with a pin and a path and bare ids (${bare.map((e) => `"${e.id}"`).join(', ')}); one line is one run of scripts/read-context.mjs, so copy the line it prints`);
      } else if (bare.some((e) => e.id.startsWith(CONFIG.globalPrefix))) {
        // The global layer came after the pin and the path, so no design was
        // ever approved with a bare global id.
        g1.fail(`${at} names ${bare.filter((e) => e.id.startsWith(CONFIG.globalPrefix)).map((e) => `"${e.id}"`).join(', ')} by id alone. A global entry is <id>@<12-hex>:${CONFIG.globalPlace}:<path>, so copy the line scripts/read-context.mjs prints`);
      } else if (bare.length) {
        designContext = new Set(ids);
        g1.note(`${at} names its documents by id alone, the form before each entry carried a pin and a path, so nobody can see which file was read or whether it has moved; accepted for now -- re-run scripts/read-context.mjs, copy the line it prints, and have the design re-reviewed`);
      } else {
        designContext = new Set(ids);
        const own = repos.length === 1 && CONFIG.repositoryPattern.test(repos[0].value) ? repos[0].value : null;
        const globalEntries = [];
        for (const e of pinned) {
          // Rule 1 of the global layer: a global id only in the global form, and
          // the global form only around a global id.
          const globalId = e.id.startsWith(CONFIG.globalPrefix);
          if (globalId && e.repository !== CONFIG.globalPlace) {
            g1.fail(`${at}: "${e.item}" is a global document and the entry places it ${e.repository === null ? 'in the hub' : `in "${e.repository}"`}. A global entry is <id>@<12-hex>:${CONFIG.globalPlace}:<path>, so copy the line scripts/read-context.mjs prints`);
            continue;
          }
          if (!globalId && e.repository === CONFIG.globalPlace) {
            g1.fail(`${at}: "${e.item}" places ${e.id} in the global layer, and a global document's id starts with "${CONFIG.globalPrefix}". Copy the line scripts/read-context.mjs prints`);
            continue;
          }
          if (globalId) {
            globalEntries.push(e);
            continue;
          }
          const keeper = e.id.match(CONFIG.spokeRecordId);
          if (keeper && keeper[1] !== e.repository) {
            g1.fail(`${at}: "${e.item}" is a decision record of "${keeper[1]}" and the entry places it ${e.repository === null ? 'in the hub' : `in "${e.repository}"`}; a record's id names the repository that keeps it, so copy the line scripts/read-context.mjs prints`);
            continue;
          }
          if (e.id.search(CONFIG.hubRecordId) === 0 && e.repository !== null) {
            g1.fail(`${at}: "${e.item}" places the hub's decision record ${e.id} in "${e.repository}"; a repository's own record is <repository-id>.ADR-<NNN>, so copy the line scripts/read-context.mjs prints`);
            continue;
          }
          if (e.repository !== null) {
            // A document kept in a repository other than the hub: this file reads
            // one remote, so the shape and the id are all it can check.
            if (own !== null && e.repository !== own) {
              g1.fail(`${at}: "${e.item}" is kept in "${e.repository}"; this design lands in "${own}", and a design reads the hub's documents and its own repository's, no other`);
            }
            continue;
          }
          const found = treeEntry(ref, e.path);
          if (found === null) {
            g1.fail(`${at}: "${e.id}" cites ${e.path}, which is not on ${ref}; a design is written against documents a person merged, so merge the document first or copy the line scripts/read-context.mjs prints`);
          } else if (found.mode === '120000' || found.type !== 'blob') {
            g1.fail(`${at}: "${e.id}" cites ${e.path}, which is ${found.mode === '120000' ? 'a symbolic link' : `a ${found.type}`} on ${ref}, not a document`);
          } else {
            const actual = blobHash(ref, e.path);
            // The commit the Hub commit: line names holds the pinned bytes, or
            // the two lines were not copied from one run.
            const held = hubCommit === null ? null : blobHash(hubCommit, e.path);
            if (actual === null) {
              g1.fail(`could not read the revision of ${e.path} on ${ref}`);
            } else if (hubCommit !== null && !(held !== null && held.startsWith(e.pin))) {
              g1.fail(`${at}: "${e.id}" pins ${e.pin} for ${e.path}, and the hub at ${hubCommit.slice(0, e.pin.length)}, the commit the ${CONFIG.hubCommitLabel}: line names, ${held === null ? 'has no file there' : `holds ${held.slice(0, e.pin.length)} there`}; the two lines were not copied from one run, so re-run scripts/read-context.mjs on an up-to-date trunk and copy the ${CONFIG.hubCommitLabel}: and ${CONFIG.contextLabel}: lines it prints`);
            } else if (!actual.startsWith(e.pin)) {
              if (hubCommit !== null && alwaysOn(pinnedBlob(e.pin))) alwaysOnIds.add(e.id);
              g1.note(`context drift: "${e.id}" (${e.path}) was ${e.pin} when the design read it and is ${actual.slice(0, e.pin.length)} on ${ref} now; the document moved after the design was written, so re-read it with scripts/read-context.mjs and decide whether the design still holds`);
            } else if (alwaysOn(readFromRef(ref, e.path))) {
              alwaysOnIds.add(e.id);
            }
          }
        }
        if (globalEntries.length) {
          // The design inherits the Global: line of the requirements document
          // its work item is cut from, found by the work item's slug. With
          // HARNESS_REPO set, a spoke's story-gate is asking with a credential
          // that cannot read the global repository (D8): the line's form and
          // its release are proved from the hub, and design-gate proved the
          // rest before the design reached the trunk.
          const remote = asking === null;
          const items = workItemEntries(ref, key);
          const source = items.length !== 1
            ? { reason: `${items.length ? `${items.length} work items` : 'no work item'} ${key}${CONFIG.itemSuffix} under ${CONFIG.backlogDir}/ on ${ref} name${items.length === 1 ? 's' : ''} the slug of its requirements document` }
            : requirementsSource(ref, items[0].path.split('/')[CONFIG.backlogDir.split('/').length]);
          globalTexts = checkGlobalEntries(ref, { entries: globalEntries, ids: new Set(ids), at, source, link: readGlobalLink(ref, g1), remote, report: g1 });
          if (!remote) {
            globalTexts = null;
            g1.note(`${globalEntries.length} global entr${globalEntries.length === 1 ? 'y' : 'ies'} checked for form and release only, as ${asking} asks without the global repository; design-gate proved the documents before the design reached ${ref}`);
          }
        }
      }
      // A line alone does not show that a document was read: each one is used
      // on the page, and each decision record and standard the page cites is
      // on the line.
      if (designContext !== null) {
        checkContextUse(ref, designLines, designs[0].path, no, value === CONFIG.contextNone ? [] : entries.filter(Boolean), g1, alwaysOnIds, globalTexts);
      }
    }
    // And to the discovery map it was written from: what the seat read in the
    // spoke, at which bytes. The repository and the rules commit come from the
    // lines above, and only when each is one well-formed line.
    const designRepo = repos.length === 1 && repos[0].value.search(CONFIG.repositoryPattern) === 0 ? repos[0].value : null;
    const rulesCite = rulesClaims.length === 1 ? rulesClaims[0].value.match(CONFIG.rulesCite) : null;
    checkDiscoveryMap(ref, key, {
      path: designs[0].path,
      lines: designLines,
      repository: designRepo,
      rulesCommit: rulesCite === null ? null : rulesCite[2],
      citedPaths: spokeCitations(designLines, designRepo),
    }, g1);
  }

  // Gate 2 -- an approved review file, verdict matched literally, written against
  // the revision of the design that is on the trunk now.
  const g2 = gate('approved review');
  const reviews = named(CONFIG.reviewSuffix);
  if (reviews.length !== 1) {
    g2.fail(`expected exactly one "*${CONFIG.reviewSuffix}" for ${key} on ${ref}, found ${reviews.length}`);
  } else {
    const reviewText = readArtefact(ref, reviews[0], g2, 'review');
    if (reviewText !== null) {
      // Masked, so a verdict quoted in an example or left in a comment is not a
      // verdict -- in either direction. A review may show the grammar without
      // failing as a duplicate, and a review whose only verdict is fenced fails
      // as "found 0" rather than opening the gate on text nobody wrote.
      const reviewLines = maskNonContent(reviewText);
      rejectHiddenMarkup(reviewLines, reviews[0].path, g2);
      rejectMalformedRows(reviewLines, reviews[0].path, g2);
      const verdicts = reviewLines.filter((l) => CONFIG.verdictLine.test(l));
      if (verdicts.length !== 1) {
        g2.fail(`${reviews[0].path} must contain exactly one verdict line, found ${verdicts.length}`);
      } else if (verdicts[0].trimEnd() !== CONFIG.approvedVerdict) {
        g2.fail(`${reviews[0].path} verdict is "${verdicts[0].trim()}"; the gate opens only on "${CONFIG.approvedVerdict}"`);
      }
      // Bounded, not a substring: a review that only ever writes PROJ-4120 has not
      // named PROJ-412.
      const mention = new RegExp(`(?:^|[^A-Za-z0-9-])${key}(?![A-Za-z0-9-])`);
      if (!reviewLines.some((l) => mention.test(l))) {
        g2.fail(`${reviews[0].path} never names ${key}; a review is evidence about one work item`);
      }
      if (designs.length === 1) {
        checkReviewRevision(ref, designs[0].path, reviews[0].path, reviewLines, g2);
      }
    }
  }

  // Gates 3 and 4 -- readiness contract and clarification table.
  const g3 = gate('readiness contract');
  const g4 = gate('clarification table');
  let values = {};
  let clarRows = [];
  if (designLines === null) {
    g3.fail('skipped: no readable design document');
    g4.fail('skipped: no readable design document');
  } else {
    const lines = designLines;
    const readinessRange = sectionRange(lines, 'Readiness', g3);
    const clarRange = sectionRange(lines, 'Clarifications', g4);
    const acRange = sectionRange(lines, CONFIG.acSection, g3);
    const testRange = sectionRange(lines, CONFIG.testSection, g3);

    values = parseReadiness(lines, readinessRange, g3);
    clarRows = parseClarTable(lines, clarRange, g4);

    // Integrity cross-check. Both numbers are DERIVED from the tables, and the
    // declared tokens are checked against the derived values -- never against
    // each other. Two integers the same author typed in the same block agreeing
    // is not evidence of a criterion-to-test map; the tables are the evidence.
    const carried = new Map();
    const criteria = parseCriteria(lines, acRange, g3, carried);
    const covered = parseTestingPlan(lines, testRange, g3);
    const acCount = values['AC count'];
    const acCovered = values['AC covered by tests'];
    const attested = values['Self-check verdict'] ? ` (author wrote "${values['Self-check verdict']}")` : '';

    if (criteria !== null && acCount !== undefined && Number(acCount) !== criteria.length) {
      g3.fail(`integrity check failed: "AC count: ${acCount}" but the "${CONFIG.acSection}" table defines ${criteria.length}${criteria.length ? `: ${criteria.join(', ')}` : ''}${attested}`);
    }
    if (covered !== null && acCovered !== undefined && Number(acCovered) !== covered.length) {
      g3.fail(`integrity check failed: "AC covered by tests: ${acCovered}" but the testing plan covers ${covered.length}${covered.length ? `: ${covered.join(', ')}` : ''}${attested}`);
    }
    if (criteria !== null && covered !== null) {
      const uncovered = criteria.filter((id) => !covered.includes(id));
      const unknown = covered.filter((id) => !criteria.includes(id));
      if (uncovered.length) {
        g3.fail(`integrity check failed: acceptance criteria with no named test in the testing plan: ${uncovered.join(', ')}${attested}`);
      }
      if (unknown.length) {
        g3.fail(`integrity check failed: the testing plan names ${unknown.join(', ')}, which the "${CONFIG.acSection}" table does not define`);
      }
    }
    // Second cross-check: the declared blocking count must match the table.
    const openBlocking = clarRows.filter((r) => r.blocking === 'yes' && CONFIG.clarOpenStatuses.includes(r.status)).length;
    const declared = values['Blocking CLAR'];
    if (declared !== undefined && Number(declared) !== openBlocking) {
      g3.fail(`integrity check failed: "Blocking CLAR: ${declared}" but the table has ${openBlocking} blocking row(s) not yet Closed or Withdrawn`);
    }
    // Third cross-check: the design's criteria trace to its work item. Without it
    // the Requirement column is checked for shape alone, so an id nobody defined
    // reaches the validation report and is repeated there as fact. The work
    // item's Carries ids were resolved against the requirements document when the
    // decomposition merged, or against the ticket snapshot when the intake merged,
    // so a row that names its criterion's own Carries id names a requirement that
    // exists. Both directions: a criterion the work item
    // does not have is one no requirement asked for, and one the design drops is a
    // requirement that quietly stops being built.
    const designPath = designs[0].path;
    const itemName = `${key}${CONFIG.itemSuffix}`;
    const itemEntries = workItemEntries(ref, key);
    if (itemEntries.length === 0) {
      g3.fail(`trace check failed: work item ${itemName} not found under ${CONFIG.backlogDir}/ on ${ref}. Merge the work item first: the design's criteria are checked against it`);
    } else if (itemEntries.length > 1) {
      // Two stories wearing one key: the gate cannot say which one the design
      // traces to, so it traces to neither and says so.
      g3.fail(`trace check failed: ${itemEntries.length} work items are filed as ${itemName} on ${ref} (${itemEntries.map((e) => e.path).join(', ')}); one key is one story, so remove the copy that is not this design's`);
    } else {
      const itemPath = itemEntries[0].path;
      const itemText = readArtefact(ref, itemEntries[0], { fail: () => {} }, 'work item');
      if (itemText !== null) {
        const itemLines = maskNonContent(itemText);
        rejectHiddenMarkup(itemLines, itemPath, g3);
        rejectMalformedRows(itemLines, itemPath, g3);
        const itemCriteria = parseWorkItem(itemLines, itemPath, key, g3);
        // The story's documents are a floor: a design is written against every
        // document its story was, and may add more. Compared by id, because the
        // design may read a document at newer bytes than the story did.
        const storyContext = contextIds(itemLines);
        if (storyContext === null) {
          g3.fail(`trace check failed: ${itemPath} carries no single well-formed "${CONFIG.contextLabel}:" line, so nothing says which documents the story was written against; /decompose writes one, and scripts/check-decomposition.js proves it`);
        } else if (designContext !== null) {
          for (const id of storyContext.filter((x) => !designContext.has(x))) {
            g3.fail(`trace check failed: ${itemPath} carries "${id}" on its "${CONFIG.contextLabel}:" line, and ${designPath} does not; a design is written against every document its story was, so name it and copy the line scripts/read-context.mjs prints`);
          }
        }
        if (itemCriteria !== null && criteria !== null) {
          for (const [id, { requirement, no }] of carried) {
            const expected = itemCriteria.get(id);
            if (!itemCriteria.has(id)) {
              g3.fail(`trace check failed: ${designPath} line ${no}: ${id} is not in the work item ${itemPath}. Use the work item's criterion ids; do not add new ones`);
            } else if (requirement !== null && expected !== null && requirement !== expected) {
              g3.fail(`trace check failed: ${designPath} line ${no}: ${id} names ${requirement}, but ${itemPath} gives ${id} ${expected}. Copy the requirement id from the work item`);
            }
          }
          for (const id of itemCriteria.keys()) {
            if (!carried.has(id)) {
              g3.fail(`trace check failed: ${id} in ${itemPath} is not in ${designPath}. Carry every work item criterion into the design`);
            }
          }
        }
      }
    }
  }

  // Report -- every gate, every finding, then exit.
  const failed = gates.filter((g) => g.failures.length > 0);
  const width = Math.max(...gates.map((g) => g.name.length));
  // The asking repository is printed for the same reason the remote URL is: the
  // verdict is only meaningful next to the question that was asked.
  const askingNote = asking === null ? '' : `, asked by ${asking}`;
  process.stdout.write(`\n${key} pickup gate  (against ${ref}, ${CONFIG.remote} -> ${remoteUrl()}${askingNote})\n\n`);
  for (const g of gates) {
    const status = g.failures.length ? 'FAIL' : 'PASS';
    process.stdout.write(`  [${status}] ${g.name.padEnd(width)}`.trimEnd() + '\n');
    for (const f of g.failures) process.stdout.write(`         - ${f}\n`);
    for (const n of g.notes) process.stdout.write(`         note: ${n}\n`);
  }
  process.stdout.write(
    failed.length
      ? `\nNOT ELIGIBLE: ${failed.length} of ${gates.length} gates failed. Tracker status is irrelevant.\n\n`
      : `\nELIGIBLE: ${gates.length} of ${gates.length} gates passed.\n\n`
  );
  process.exit(failed.length ? EXIT.GATE_FAIL : EXIT.PASS);
}

// The last line of an exit 2, 3 or 4 names this script and its code, so a shell line that hides
// the code, with a pipe or `; echo`, still tells the harness's failure record. Written at once,
// so a process.exit() never loses it.
process.on('exit', (code) => { if (code >= 2 && code <= 4) { try { writeSync(2, `HARNESS EXIT: check-dev-ready ${code}\n`); } catch { /* stderr is closed */ } } });

try {
  main();
} catch (err) {
  process.stderr.write(`INTERNAL ERROR: ${err && err.stack ? err.stack : String(err)}\n`);
  process.exit(EXIT.INTERNAL);
}
