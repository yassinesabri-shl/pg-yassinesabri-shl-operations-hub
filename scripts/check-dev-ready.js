#!/usr/bin/env node
/**
 * check-dev-ready.js — the executable pickup gate.
 *
 * This file is the SINGLE SOURCE OF TRUTH for the pickup gate. Gate logic lives
 * nowhere else: not in a runbook, not in an agent prompt, not duplicated in CI.
 * If a rule is not in this file, it is not a gate.
 *
 *   usage:  node scripts/check-dev-ready.js PROJ-412
 *
 * Exit codes
 *   0  every gate passed              -> the work item is eligible for build
 *   1  at least one gate failed       -> not eligible; all findings printed
 *   2  cannot verify                  -> refused to judge (stale or unreachable remote)
 *   3  usage error                    -> bad or missing work-item key
 *   4  internal error                 -> unexpected; treat as not eligible
 *
 * Design notes
 *   - Reads the DEFAULT BRANCH, never the working tree. A design that only
 *     exists on a feature branch has not been approved. The branch name is
 *     confirmed against the remote's own default branch, so naming a branch in
 *     the environment cannot point the gate at the author's own work.
 *   - Reads the document a human reads. Fenced and indented code blocks, HTML
 *     and MDX comments, raw-text HTML blocks and link reference definitions are
 *     blanked once, where text becomes lines, so no parser downstream can be
 *     shown content the rendered page does not show. See maskNonContent().
 *   - Refuses markup that leaves content in the file but not in front of the
 *     reader -- a collapsed <details>, an HTML <table>, a `display:none` style.
 *     Masking cannot help there: the content is real, so the gate says where it
 *     is instead of reading it. See findHiddenMarkup().
 *   - DERIVES the criterion-to-test map from the acceptance-criteria table and
 *     the testing-plan table, then checks the declared counts against the
 *     derived ones. Two numbers typed by the same author agreeing with each
 *     other is not evidence; only the tables are evidence.
 *   - Parses sections 4, 5, 8 and 9. Headings are locators, so the section
 *     numbers are optional; field labels and values are matched literally.
 *   - Requires the criteria table to name, for every criterion, the requirement
 *     criterion it carries: a `Requirement` column, found by name, every cell
 *     exactly one `REQ-<n>.AC-<m>`, or `JIRA-<KEY>.AC-<m>` for a story taken
 *     from a Jira ticket. That is how the requirement id reaches the
 *     validation report, where check-validation.js reads the same column.
 *   - TRACES the criteria table to the work item it was written from, a
 *     `docs/backlog/<SLUG>/<KEY>.item.md` on the trunk: the design carries
 *     exactly the work item's criteria, and every `Requirement` id is the one
 *     the work item's `Carries` column gives that criterion. The decomposition
 *     check resolved every `Carries` id against the requirements document when
 *     the decomposition merged, so a design that traces names only requirement
 *     criteria that exist, each against the right criterion. A story taken
 *     from a ticket sits under the reserved slug `jira`, and carries only
 *     `JIRA-<its own key>.AC-<m>`, which check-intake.js resolved against the
 *     ticket snapshot when the intake merged. Any other story carries only
 *     `REQ-<n>.AC-<m>`. No work item on the trunk, two work items for one key,
 *     or one whose criteria table cannot be read, is a failure.
 *   - Binds the review to the REVISION it approved: the review carries the
 *     design's blob hash, and one changed byte invalidates it.
 *   - Force-fetches first. A silent stale remote ref is exactly the bug this
 *     script exists to prevent, so failure to fetch exits 2 rather than 1 --
 *     "cannot verify" is a different fact from "verified and failed".
 *   - Runs EVERY gate before exiting. No short-circuit. One run gives the
 *     author the complete list of what to fix.
 *   - Node standard library only, plus git via child_process.
 *   - ES module. If your package.json is not { "type": "module" }, save this
 *     file as check-dev-ready.mjs and the shebang still works.
 *   - Non-`main` trunk: set HARNESS_TRUNK=<branch>. It must name the remote's
 *     actual default branch or the gate exits 2. Do not edit this file.
 *   - Binds the design to the REPOSITORY its code lands in: exactly one
 *     `Repository: <id>` line. When the gate is run from another repository's
 *     CI, that repository sets HARNESS_REPO=<its id> and the line must match,
 *     so a design written for one repository cannot admit code into another.
 *     The design also names the RULES it was written under: exactly one
 *     `Rules: none` or `Rules: <id>@<12-hex>:<path>` line, the id matching the
 *     `Repository:` line, so a sprint can tell whether the repository's own
 *     rules have moved since the design read them. And it names the CONTEXT
 *     documents it was written against: exactly one `Context: none` or
 *     `Context: <id>@<12-hex>:<path>, ...` line, as `scripts/read-context.mjs`
 *     prints it -- each entry the document's id, the blob hash of the bytes the
 *     design read, and where the file is (`<repository-id>:<path>` for one
 *     kept in the design's own repository). Beside it, exactly one
 *     `Hub commit: <40-hex>` line names the hub commit the script read the
 *     hub's documents at: it must be on the trunk and hold every hub entry's
 *     bytes at its path, or the two lines were not copied from one run, and
 *     the gate fails. A hub document must be on the trunk; one whose bytes
 *     have moved since is printed as a context-drift note and does not fail
 *     the gate. A shallow clone that cannot see the hub commit exits 2. A line
 *     alone does not show that a document was
 *     read, so the design must also use each one where a reader sees it: its
 *     id named outside the line, and a standard cited by a rule it defines,
 *     `std-<topic>.<NN>`. Each decision record and standard rule the design
 *     cites is on the line. And the work item's own `Context:` line is a
 *     floor: each id on it is on the design's, compared by id.
 *   - The design may name the Prime Security guardrails it chose: at most one
 *     `Guardrails:` line, `off`, `none`, `unchecked` or
 *     `prime@<12-hex>:<id>, <id>, ...` as scripts/prime.mjs choose prints it.
 *     No line reads as `off`. The gate checks the form only and never asks
 *     Prime; /dev-sprint reads the rules again with prime.mjs refresh.
 *   - A third entry form names a document of the global context repository,
 *     `<id>@<12-hex>:global:<path>` (docs/proposals/global-context.md §8). Its
 *     id starts with `global.`, and a `global.` id appears in no other form. Its
 *     pin is the global commit on the `Global:` line of the requirements
 *     document the work item's slug names. A hub without docs/estate/global.json
 *     has no global layer and refuses every global entry. The gate reads the
 *     global repository through a bare cache outside the hub, as the hub reads a
 *     spoke: the path is at the commit, its header names the entry's id, a
 *     global standard's cited rules are ones it defines, and an exception is
 *     Active, names this hub by its key prefix (docs/backlog/keys.json), and
 *     sits on the line beside every record it departs from. An exception past
 *     its review-by date is a note. A global repository that does not answer is
 *     exit 2. With HARNESS_REPO set, a spoke's story-gate is asking, and its
 *     credential cannot read the global repository (D8): the gate then proves
 *     the entry's form and its commit from the hub alone and reads no global
 *     repository. design-gate proved the rest before the design merged.
 *     Unset, or empty, means the repository holding the design is asking about
 *     its own work and the line only has to exist and be well formed.
 *   - Discovery. A design pins the discovery map it was written from: one
 *     `Discovery: <KEY>.discovery.md@<12-hex>` line. The map sits beside the
 *     design on the trunk and lists the spoke files the seat read, the
 *     searches it ran, the paths it ruled out and the rows it reused from an
 *     earlier story's map. The pin is the first 12 characters of the map's
 *     blob hash, so a map that changed after the design pinned it fails. The
 *     map names the design's key, its repository and a commit. When `Rules:`
 *     is not `none`, the commit starts with the design's `Rules:` commit. Each
 *     table follows the map grammar in
 *     CONFIG. Each spoke path the design cites is a read in the map. A reused
 *     row names a map pin that a commit on the trunk held, and a shallow clone
 *     that would have to answer that exits 2. A design with no line and no map
 *     was written before /dev-spec wrote maps. It passes with a note. A design
 *     with no line and a map on the trunk fails.
 *
 * What this gate cannot see
 *   - Whether the repository a design names exists, or is the one the team
 *     meant. The gate reads one remote, the one holding the design, and the
 *     list of repositories lives elsewhere. HARNESS_REPO is the caller's
 *     claim about itself, checked for shape and for equality, not for truth.
 *   - Whether a document a `Context:` line keeps in another repository exists,
 *     or has moved: the gate reads the hub's remote, and the global repository
 *     for a global entry, so a spoke's entry is checked for shape and for the
 *     repository id. Nor whether a design contradicts a global record: that is
 *     the critic's judgement. Nor whether the entries are the ones
 *     `scripts/read-context.mjs` would select for this design: the selection
 *     is the script's, and whether the line is the one it printed is the
 *     critic's finding. Nor whether a cited rule is followed where it is
 *     cited: the gate sees the citation, the critic reads the design.
 *   - Whether the map lists every read the seat made: the critic's finding.
 *     Nor whether a blob in the map is the file's real blob at the map's
 *     commit: the gate reads one remote, and the spoke is another.
 *   - Whether a named test exists, or would pass, or asserts anything. It runs
 *     before build, so the test is legitimately not written yet. A well-formed
 *     name in the test-name column is the whole of the evidence; existence and
 *     behaviour belong to a later gate.
 *   - Whether a criterion is true, complete, or the right criterion. Every
 *     check below is on the SHAPE of the document. A design with four fluent,
 *     well-cited criteria that describe the wrong system passes all four gates.
 *   - Whether the review is any good, or was written by anyone but the author.
 *     It checks the verdict token, not the judgement behind it, and git
 *     authorship is configuration. Separation of duty here is procedure, not a
 *     permission boundary.
 *   - Whether a clarification was actually answered. `Closed` plus a resolution
 *     plus a past date is what the gate can check; whether the specification
 *     was truly amended, it cannot.
 *   - Whether the work-item key was ever raised in a tracker.
 *   - A second design outside docs/designs. "Exactly one" is scoped to that
 *     directory.
 *   - Which remote `origin` resolves to. A repointed remote produces a pass
 *     byte-identical to an honest one, so the URL is printed in the header: the
 *     substitution then sits in the transcript next to the verdict.
 *   - The difference between markdown a renderer reads the way this file does
 *     and the handful of constructs where it does not. The mask is a line
 *     scanner, not a CommonMark parser.
 *   - YAML front matter, which carries no special status: a readiness label
 *     used as a front-matter key is read as a second occurrence of the field.
 */

