#!/usr/bin/env node
// Part of the harness asset library c6f3b4427d58f7c3 (see VERSION.json) · 2026-10-01
/**
 * check-watermark.mjs — the harness watermark, on commits and on pull requests.
 *
 * Every commit the installed harness makes in a hub or a spoke, and every pull request it opens
 * there, ends with this exact final
 * non-empty line (`rules/watermark.md` is the rule) — a git trailer, the last line of the
 * message's trailer block, so Co-authored-by and Signed-off-by trailers before it stay trailers:
 *
 *     Generated-by: SHL Agentic Harness
 *
 * It is a visible label that tells harness-generated work from a person's. It is not
 * cryptographic proof: anyone can type it. This file is the single source of truth for the
 * check; `harness-commit.mjs` imports it.
 *
 *   usage:  node scripts/check-watermark.mjs --commit-msg <file>
 *           node scripts/check-watermark.mjs --pr-body <file> <base>..<head>
 *
 *   --commit-msg  the commit-msg hook. A harness-managed commit — made by harness-commit.mjs
 *                 (HARNESS_COMMIT=1 in the environment), or whose message carries the
 *                 watermark phrase anywhere — must end with the watermark. Its comment lines and
 *                 scissors section are dropped before the check, and the message file is
 *                 rewritten to the checked text, so what was checked is what git stores. Any
 *                 other commit is a person's and passes untouched, its file unread.
 *   --pr-body     the pull-request check: the description as the pull-request event carries it
 *                 (never a file from the branch), and every non-merge commit of <base>..<head>.
 *
 * The form, read literally — a variant is a failure, not something to normalise:
 *   - the final non-empty line is exactly the watermark: case-sensitive, no leading or trailing
 *     space, nothing added — no Markdown, quote, list marker or code formatting;
 *   - git reads it as a trailer: it is the last line of the trailer block `git interpret-trailers
 *     --parse` finds, so it stands alone or directly under other trailers, never under prose;
 *   - the phrase appears once, so not also in the middle;
 *   - the line is not inside a code block or an HTML comment;
 *   - everything else, Co-authored-by and Signed-off-by trailers included, comes before it.
 * A text "claims" the watermark when it holds the phrase in any case, spacing or punctuation —
 * the earlier "Generated by SHL Agentic Harness" included. A claim that is not in the form is a
 * missing, misplaced or modified watermark.
 *
 * The pull-request rules, all run before it exits:
 *   1. a non-merge commit claims the watermark → the description must end with it;
 *   2. the description claims it → at least one non-merge commit must carry it;
 *   3. a commit that does not claim it is a person's, and passes untouched, in any pull request;
 *   4. neither the commits nor the description claim it → a person's pull request, unchanged;
 *   5. every claim, on a commit or the description, must be in the form.
 * Merge commits are not read: the merges people make carry no watermark and need none.
 *
 * Exit codes, shared with every check in the library:
 *   0 pass  1 a rule failed, every failure listed  2 cannot verify: no description file, a
 *   range that does not resolve, a shallow clone  3 usage  4 internal
 *
 * Node standard library only, plus git via child_process.
 */

import { execFileSync } from 'node:child_process';
import { existsSync, readFileSync, realpathSync, writeFileSync, writeSync } from 'node:fs';
import { fileURLToPath } from 'node:url';

export const WATERMARK = 'Generated-by: SHL Agentic Harness';
const PHRASE = /generated[\s_-]*by[\s:_-]*shl[\s_-]*agentic[\s_-]*harness/gi;
const EXIT = { PASS: 0, FAIL: 1, CANNOT_VERIFY: 2, USAGE: 3, INTERNAL: 4 };

/** Whether a text holds the watermark phrase anywhere, in any case, spacing or punctuation. */
export const claims = (text) => new RegExp(PHRASE.source, 'i').test(String(text ?? ''));

/** Null when the text ends with the watermark in its one valid form; else why not. */
export function watermarkProblem(text) {
  const s = String(text ?? '').replace(/\r\n?/g, '\n');
  const lines = s.split('\n');
  let last = lines.length - 1;
  while (last >= 0 && lines[last].trim() === '') last -= 1;
  if (last < 0) return 'it is empty';
  let fence = null;
  let comment = false;
  for (const line of lines.slice(0, last)) {
    if (comment) {
      // A line may close the comment and open another; only text after the last opener counts.
      const close = line.indexOf('-->');
      if (close < 0) continue;
      const reopen = line.lastIndexOf('<!--');
      comment = reopen > close && !line.slice(reopen).includes('-->');
      continue;
    }
    const f = line.match(/^ {0,3}(`{3,}|~{3,})/);
    if (fence) {
      if (f && f[1][0] === fence[0] && f[1].length >= fence.length && line.trim() === f[1]) fence = null;
      continue;
    }
    if (f) { fence = f[1]; continue; }
    const open = line.lastIndexOf('<!--');
    if (open >= 0 && !line.slice(open).includes('-->')) comment = true;
  }
  const final = lines[last];
  if (final !== WATERMARK) {
    if (claims(final)) return `its final line "${final}" is a modified watermark; it must be exactly "${WATERMARK}"`;
    if (claims(s)) return `the watermark is not its final line (the final line is "${final}")`;
    return `it does not end with the line "${WATERMARK}"`;
  }
  if (fence) return 'the watermark sits inside a code block';
  if (comment) return 'the watermark sits inside an HTML comment';
  const count = (s.match(PHRASE) || []).length;
  if (count !== 1) return `the watermark phrase appears ${count} times; once, as the final line`;
  const trailers = execFileSync('git', ['-c', 'trailer.separators=:', 'interpret-trailers', '--parse'], { input: s, encoding: 'utf8' }).trimEnd().split('\n');
  if (trailers[trailers.length - 1] !== WATERMARK) return 'git does not read the watermark as a trailer: it must stand in the final paragraph alone or directly under other trailers, not under prose';
  return null;
}

/** A commit message without its comment lines and anything below a scissors line. */
export function cleanMessage(text, commentChar = '#') {
  const lines = String(text ?? '').replace(/\r\n?/g, '\n').split('\n');
  const cut = lines.findIndex((l) => l.startsWith(`${commentChar} `) && / -+ >8 -+$/.test(l));
  return (cut >= 0 ? lines.slice(0, cut) : lines).filter((l) => !l.startsWith(commentChar)).join('\n');
}

/** The comment character git uses here: core.commentChar, or '#'. */
export function commentChar(cwd = '.') {
  try {
    const c = execFileSync('git', ['-C', cwd, 'config', '--get', 'core.commentChar'], { encoding: 'utf8', stdio: ['ignore', 'pipe', 'ignore'] }).trim();
    return c && c !== 'auto' ? c[0] : '#';
  } catch (err) { return '#'; }
}

/* ------------------------------------------------------------------- the two modes */

function git(args) {
  return execFileSync('git', args, { encoding: 'utf8', stdio: ['ignore', 'pipe', 'pipe'], maxBuffer: 1 << 26 });
}

function cannot(message, token) {
  process.stderr.write(`CANNOT VERIFY: ${message}\n`);
  // This line names the cause as a fixed token, for the harness's failure record, just before the
  // exit line that the exit handler writes. The token
  // must be on REASONS in scripts/spoke-remote.mjs, and the check of the tokens proves it.
  if (token) process.stderr.write(`REASON: ${token}\n`);
  process.exit(EXIT.CANNOT_VERIFY);
}

// Git cleans the message after this hook runs, by a mode the hook cannot see (--cleanup, or the
// default: strip when an editor ran, whitespace otherwise). So a harness-managed message is
// checked without its comment lines and scissors section, and on success the file is rewritten to
// exactly that text: every cleanup mode then leaves the checked bytes as they are, and the
// watermark the hook approved is the line git stores last.
function checkCommitMsg(file) {
  if (!existsSync(file)) cannot(`no message file at ${file}; the commit-msg hook passes it as its first argument`, 'file-unreadable');
  const raw = readFileSync(file, 'utf8');
  if (process.env.HARNESS_COMMIT !== '1' && !claims(raw)) return EXIT.PASS; // a person's commit
  const message = cleanMessage(raw, commentChar());
  const problem = watermarkProblem(message);
  if (!problem) {
    const stored = `${message.replace(/\s+$/, '')}\n`;
    if (stored !== raw) writeFileSync(file, stored);
    return EXIT.PASS;
  }
  process.stdout.write(`FAIL the harness commit's message: ${problem}\nWATERMARK FAILED — the commit was not created.\n`);
  return EXIT.FAIL;
}

function checkPullRequest(bodyFile, range) {
  if (!existsSync(bodyFile)) cannot(`no pull request description at ${bodyFile}; pass the one the pull-request event carries`, 'file-unreadable');
  if (git(['rev-parse', '--is-shallow-repository']).trim() === 'true') cannot('this clone is shallow, so the range may be missing commits; fetch with full history', 'shallow-clone');
  let shas;
  try {
    shas = git(['rev-list', '--no-merges', '--reverse', range]).split('\n').filter(Boolean);
  } catch (err) {
    cannot(`the range ${range} does not resolve here (${(err.stderr || err.message).trim().split('\n')[0]})`, 'commit-not-found');
  }
  const body = readFileSync(bodyFile, 'utf8');
  const commits = shas.map((sha) => ({ sha, message: git(['log', '-1', '--format=%B', sha]) }));
  const marked = commits.filter((c) => claims(c.message));
  const prClaims = claims(body);
  if (marked.length === 0 && !prClaims) {
    process.stdout.write(`WATERMARK OK — a person's pull request: none of its ${commits.length} non-merge commit(s) nor its description carries the watermark.\n`);
    return EXIT.PASS;
  }
  const findings = [];
  for (const c of marked) {
    const problem = watermarkProblem(c.message);
    if (problem) findings.push(`commit ${c.sha.slice(0, 12)}: ${problem}`);
  }
  const bodyProblem = watermarkProblem(body);
  if (bodyProblem) findings.push(`the pull request description: ${bodyProblem}${prClaims ? '' : ` — its commits carry the watermark, so the description must end with it`}`);
  if (prClaims && marked.length === 0) findings.push(`the pull request description carries the watermark, and none of its ${commits.length} non-merge commit(s) does; a harness pull request holds at least one harness commit`);
  if (findings.length === 0) {
    const people = commits.length - marked.length;
    process.stdout.write(`WATERMARK OK — a harness pull request: ${marked.length} watermarked commit(s)${people ? ` and ${people} person's commit(s), passed untouched,` : ''} and the description ending with "${WATERMARK}".\n`);
    return EXIT.PASS;
  }
  for (const f of findings) process.stdout.write(`FAIL ${f}\n`);
  process.stdout.write(`WATERMARK FAILED — ${findings.length} finding(s) over ${commits.length} non-merge commit(s) and the description.\n`);
  return EXIT.FAIL;
}

function usage(message) {
  process.stderr.write(`${message}\nusage: node ${process.argv[1]} --commit-msg <file>\n       node ${process.argv[1]} --pr-body <file> <base>..<head>\n`);
  process.exit(EXIT.USAGE);
}

function main(argv) {
  if (argv[0] === '--commit-msg' && argv.length === 2) return checkCommitMsg(argv[1]);
  if (argv[0] === '--pr-body' && argv.length === 3) {
    if (!/^[^.].*[^.]$/.test(argv[2]) || !argv[2].includes('..') || argv[2].includes('...')) usage(`a range is <base>..<head>: got "${argv[2]}"`);
    return checkPullRequest(argv[1], argv[2]);
  }
  return usage('ask one thing: --commit-msg <file>, or --pr-body <file> <base>..<head>');
}

const invoked = (() => { try { return realpathSync(process.argv[1] || '') === realpathSync(fileURLToPath(import.meta.url)); } catch (err) { return false; } })();
if (invoked) {
  // The last line of an exit 2, 3 or 4 names this script and its code, so a shell line that hides
  // the code, with a pipe or `; echo`, still tells the harness's failure record. Written at once,
  // so a process.exit() never loses it.
  process.on('exit', (code) => { if (code >= 2 && code <= 4) { try { writeSync(2, `HARNESS EXIT: check-watermark ${code}\n`); } catch { /* stderr is closed */ } } });
  try {
    process.exit(main(process.argv.slice(2)));
  } catch (err) {
    process.stderr.write(`INTERNAL: ${err && err.stack ? err.stack : String(err)}\n`);
    process.exit(EXIT.INTERNAL);
  }
}
