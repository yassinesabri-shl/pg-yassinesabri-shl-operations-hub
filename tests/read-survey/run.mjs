const NONE = 'None found.';

function table(header, rows) {
  if (typeof rows === 'string') return rows;
  return [`| ${header.join(' | ')} |`, `|${header.map(() => '---').join('|')}|`, ...rows.map((r) => `| ${r.join(' | ')} |`)].join('\n');
}

/** A survey as text. `rows` gives each table's rows as [key, cell, path, a, b] (stores: [key, access, objects, path, a, b]). */
function survey(id, commit, { serves = NONE, calls = NONE, stores = NONE, libs = NONE, third = NONE, notRead } = {}) {
  const e = (path, a, b) => `${id}@${commit.slice(0, 12)}:${path} L${a}-${b}`;
  const three = (rows) => (typeof rows === 'string' ? rows : rows.map(([k, c, p, a, b]) => [k, c, e(p, a, b)]));
  const four = (rows) => (typeof rows === 'string' ? rows : rows.map(([k, acc, obj, p, a, b]) => [k, acc, obj, e(p, a, b)]));
  return [
    '---', 'kind: service-survey', `repository: ${id}`, `commit: ${commit}`, 'template: service-survey v4', '---', '',
    `# Service survey: ${id}`, '', DISCLAIMER, '',
    '## 1. Serves', '', table(['Key', 'What', 'Evidence'], three(serves)), '',
    '## 2. Calls', '', table(['Key', 'Provider', 'Evidence'], three(calls)), '',
    '## 3. Data stores', '', table(['Key', 'Access', 'Objects', 'Evidence'], four(stores)), '',
    '## 4. Shared libraries', '', table(['Key', 'Version', 'Evidence'], three(libs)), '',
    '## 5. Third-party libraries', '', table(['Key', 'Version', 'Evidence'], three(third)), '',
    '## 6. Open points', '', 'None.', '',
    // Template v6 and section 7 only when `notRead` is given. The other fixtures stay on v4.
    ...(notRead === undefined ? [] : ['## 7. Not read', '', table(['Rule', 'Folder', 'Files', 'Bytes'], notRead), '']),
  ].join('\n').replace('template: service-survey v4', notRead === undefined ? 'template: service-survey v4' : 'template: service-survey v6');
}

function registry(entries) {
  return `${JSON.stringify({ schema_version: 1, repositories: entries }, null, 2)}\n`;
}

