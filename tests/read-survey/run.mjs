/** svc serves transfers, calls batch's postings, writes the ledger store; batch serves postings and reads the store. */
const svcSurvey = (commit) => survey('svc', commit, {
  serves: [['http:POST:/transfers', 'Creates a transfer', 'src/routes.js', 1, 4]],
  calls: [['http:POST:/postings', 'batch', 'src/ledger.js', 2, 4]],
  stores: [['store:postgres:ledger', 'write', 'postings', 'src/db.js', 1, 3]],
});
const batchSurvey = (commit) => survey('batch', commit, {
  serves: [['http:POST:/postings', 'Records a posting', 'src/routes.js', 2, 6]],
  stores: [['store:postgres:ledger', 'read', 'postings', 'src/db.js', 4, 6]],
});

function estate(root, { svcUrl, batchUrl, extra = {} } = {}) {
  const svc = makeRemote(root, 'svc');
  const batch = makeRemote(root, 'batch');
  const reg = registry({ svc: entry(svc, svcUrl), batch: entry(batch, batchUrl), ...extra });
  return { svc, batch, reg };
}

