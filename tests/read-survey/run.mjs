#!/usr/bin/env node
/**
 * run.mjs — the fixture suite for read-survey.mjs.
 *
 *   usage:  node run.mjs            run every fixture
 *           node run.mjs 2 6        run only the numbered fixtures
 *           node run.mjs --keep     leave the throwaway repositories on disk
 *
 * A fixture is a REPOSITORY STATE: a throwaway hub checkout on disk holding the
 * list of repositories and the surveys, and real bare remotes for the surveyed
 * repositories, some moved on since they were surveyed. The shipped script is
 * run from the hub as a planning seat runs it, and exit code and report text
 * are asserted. Fixture 1 is the valid control; most others change one thing.
 *
 * Node standard library only, plus git via child_process. No test framework.
 * Exit 0 if every fixture passes, 1 if any fails.
 */

