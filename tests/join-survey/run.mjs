function expectEqual(actual, expected) {
  const a = JSON.stringify(actual);
  const e = JSON.stringify(expected);
  if (a !== e) throw new Error(`expected ${e}, got ${a}`);
}

function runFixture(fixture) {
  const root = mkdtempSync(join(tmpdir(), `join-survey-fx${String(fixture.n).padStart(2, '0')}-`));
  try {
    const dir = join(root, 'clone.parts');
    mkdirSync(dir);
    // rawPlan null leaves plan.json out.
    const planText = planJson(fixture.plan || ['P1', 'P2'], fixture.excluded || [], fixture.manifests);
    if (fixture.rawPlan !== null) writeFileSync(join(dir, 'plan.json'), fixture.rawPlan ? fixture.rawPlan(planText) : planText);
    for (const [name, body] of Object.entries(fixture.files)) writeFileSync(join(dir, name), typeof body === 'function' ? body() : body);
    const out = join(root, 'hub', 'docs', 'estate', 'surveys', `${ID}.md`);
    const res = fixture.argv
      ? spawnSync(process.execPath, [SCRIPT, ...fixture.argv(dir, out)], { env: ENV, encoding: 'utf8' })
      : join_(dir, out);
    if (fixture.argv && existsSync(out)) throw new Error('--check wrote --out');
    const output = `${res.stdout || ''}${res.stderr || ''}`;
    const problems = [];
    if (res.status !== fixture.exit) problems.push(`expected exit ${fixture.exit}, got ${res.status}`);
    for (const needle of fixture.includes || []) {
      if (!output.includes(needle)) problems.push(`output does not contain: ${JSON.stringify(needle)}`);
    }
    for (const needle of fixture.excludes || []) {
      if (output.includes(needle)) problems.push(`output should not contain: ${JSON.stringify(needle)}`);
    }
    const lines = output.split('\n');
    for (const start of fixture.starts || []) {
      if (!lines.some((l) => l.startsWith(start))) problems.push(`no output line starts with: ${JSON.stringify(start)}`);
    }
    if (res.status !== 0 && existsSync(out)) problems.push('--out was written on a failed join');
    if (fixture.check && res.status === 0) {
      try {
        fixture.check(readFileSync(out, 'utf8'), { root, dir, out });
      } catch (err) {
        problems.push(err.message);
      }
    }
    if (fixture.then && !problems.length) {
      try {
        fixture.then({ root, dir, out });
      } catch (err) {
        problems.push(err.message);
      }
    }
    return { problems, output };
  } catch (err) {
    return { problems: [`fixture failed: ${err && err.message ? err.message : String(err)}`], output: '' };
  } finally {
    if (!process.argv.includes('--keep')) rmSync(root, { recursive: true, force: true });
  }
}

function main() {
  const wanted = process.argv.slice(2).filter((a) => a.search(/^\d+$/) >= 0).map(Number);
  const selected = wanted.length ? FIXTURES.filter((f) => wanted.includes(f.n)) : FIXTURES;
  let failed = 0;
  for (const fixture of selected) {
    const { problems, output } = runFixture(fixture);
    if (problems.length) {
      failed += 1;
      process.stdout.write(`  FAIL  ${fixture.n}. ${fixture.name} [exit ${fixture.exit}]\n`);
      for (const p of problems) process.stdout.write(`          - ${p}\n`);
      process.stdout.write(`${output.split('\n').map((l) => `          | ${l}`).join('\n')}\n`);
    } else {
      process.stdout.write(`  PASS  ${fixture.n}. ${fixture.name} [exit ${fixture.exit}]\n`);
    }
  }
  process.stdout.write(failed
    ? `\n${failed} of ${selected.length} fixtures FAILED. The join is not proven until this is green.\n`
    : `\nAll ${selected.length} fixtures passed.\n`);
  rmSync(SANDBOX_HOME, { recursive: true, force: true });
  process.exit(failed ? 1 : 0);
}

