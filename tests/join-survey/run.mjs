function planJson(ids, excluded = [], manifests = MANIFESTS) {
  return `${JSON.stringify({
    repository: ID,
    commit: COMMIT,
    budget: 250000,
    mode: 'full',
    reason: 'no previous survey',
    parts: ids.map((id) => ({ id, bytes: 100, paths: ['./'], files: [{ path: 'src/a.js', bytes: 100 }], rows: [] })),
    excluded,
    manifests,
    notManifests: [],
  }, null, 2)}\n`;
}

function join_(dir, out) {
  return spawnSync(process.execPath, [SCRIPT, '--parts', dir, '--out', out], { env: ENV, encoding: 'utf8' });
}

