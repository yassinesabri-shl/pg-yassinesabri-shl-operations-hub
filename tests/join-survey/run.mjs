function table(header, rows) {
  if (typeof rows === 'string') return rows;
  return [`| ${header.join(' | ')} |`, `|${header.map(() => '---').join('|')}|`, ...rows.map((r) => `| ${r.join(' | ')} |`)].join('\n');
}

/**
 * A partial survey as text, with the cell defaults of survey() in the
 * check-survey suite. A part set to null is left out, and `raw` replaces the
 * whole file.
 */
function part(id, o = {}) {
  const commit = o.commit || COMMIT;
  const e = (path, a, b) => ev(path, a, b, commit);
  const parts = {
    front: ['---', 'kind: service-survey-part', `repository: ${ID}`, `commit: ${commit}`, 'template: service-survey v5', `part: ${id}`, '---'].join('\n'),
    title: `# Service survey: ${ID}`,
    disclaimer: DISCLAIMER,
    serves: [
      ['http:GET:/transfers/{id}', 'Returns one transfer', e('src/routes.js', 3, 5)],
      ['http:POST:/transfers', 'Creates a transfer', `${e('src/routes.js', 7, 12)}, ${e('src/db.js', 2, 3)}`],
    ],
    calls: [['http:POST:/postings', 'batch', e('src/ledger.js', 2, 4)]],
    stores: [['store:postgres:transfers', 'read-write', 'transfers, transfer_events', e('src/db.js', 1, 6)]],
    libs: NONE,
    third: NONE,
    open: 'None.',
    ...o,
  };
  if (parts.raw !== undefined) return parts.raw;
  const out = [parts.front, '', parts.title, '', parts.disclaimer, ''];
  const add = (heading, header, rows) => out.push(heading, '', table(header, rows), '');
  add('## 1. Serves', ['Key', 'What', 'Evidence'], parts.serves);
  add('## 2. Calls', ['Key', 'Provider', 'Evidence'], parts.calls);
  add('## 3. Data stores', ['Key', 'Access', 'Objects', 'Evidence'], parts.stores);
  add('## 4. Shared libraries', ['Key', 'Version', 'Evidence'], parts.libs);
  add('## 5. Third-party libraries', ['Key', 'Version', 'Evidence'], parts.third);
  out.push('## 6. Open points', '', table(OPEN, parts.open), '');
  return out.join('\n');
}

const EMPTY = { serves: NONE, calls: NONE, stores: NONE };

